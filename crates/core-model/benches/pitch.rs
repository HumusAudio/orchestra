//! Instruction-count benchmarks of the pitch operations (ADR-0023, SCALETTA F1.07).
//!
//! # Why these operations
//! The playback compile (F1.13) turns every written note into a performed one: it computes the
//! MIDI key and bend of each notehead, and the written pitch of each note of a transposing
//! instrument. Score entry and MIDI import spell keys in a key. These run once per note over whole
//! scores (≈ 256 000 notes in the heavy score of ADR-0022), so their cost is measured.
//!
//! # Batches and setup
//! Each benchmark runs its operation on a batch of 64 inputs (ADR-0017 §4: a single call is too
//! small and drifts by an instruction when unrelated code changes); divide by 64 for one call. The
//! inputs are built by the argument expression, which Gungraun evaluates outside the measured
//! region, and the results go through `black_box` so that nothing is optimised away.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
// The setup functions build inputs from constants known to be valid: a failure there is a bug of
// the benchmark itself and should stop it loudly.
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid constants; never part of the measured code"
)]
// Gungraun moves each benchmark's input into the function (so that building it is not measured),
// and the batches of `Copy` pitches are larger than clippy's 256-byte threshold for passing by value.
#![allow(
    clippy::large_types_passed_by_value,
    reason = "Gungraun passes the prepared batch by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::pitch::{Alteration, Interval, Key, Mode, Pitch, Quality, Step};
use orchestra_core_time::Rational;

const BATCH: usize = 64;

// 64 pitches over the whole keyboard: every step, alterations from double flat to double sharp,
// one in eight a quarter tone (so that the bend path is measured too).
fn pitches() -> [Pitch; BATCH] {
    std::array::from_fn(|i| {
        let i = i64::try_from(i).unwrap();
        let alteration = if i % 8 == 7 {
            Alteration::new(Rational::new(1, 2).unwrap()).unwrap()
        } else {
            Alteration::chromatic(i % 5 - 2).unwrap()
        };
        let octave = i8::try_from(1 + i % 7).unwrap();
        Pitch::new(Step::from_index(i), alteration, octave)
    })
}

// The transposing-instrument intervals the playback compile applies most: B♭ clarinet, horn in
// F, E♭ alto saxophone, piccolo, cycled over the batch.
fn transpositions() -> ([Pitch; BATCH], [Interval; BATCH]) {
    let intervals = [
        Interval::from_quality(Quality::Major, 2, true).unwrap(),
        Interval::from_quality(Quality::Perfect, 5, true).unwrap(),
        Interval::from_quality(Quality::Major, 6, true).unwrap(),
        Interval::from_quality(Quality::Perfect, 8, false).unwrap(),
    ];
    (
        pitches(),
        std::array::from_fn(|i| intervals[i % 4].reversed()),
    )
}

// 64 MIDI keys and keys: every pitch class, keys from six flats to six sharps, major and minor.
fn midi_keys() -> [(u8, Key); BATCH] {
    std::array::from_fn(|i| {
        let key = u8::try_from(36 + i).unwrap();
        let fifths = i8::try_from(i % 13).unwrap() - 6;
        let mode = if i % 2 == 0 { Mode::Major } else { Mode::Minor };
        (key, Key::traditional(fifths, mode).unwrap())
    })
}

#[library_benchmark]
#[bench::batch(pitches())]
fn midi(pitches: [Pitch; BATCH]) -> [Pitch; BATCH] {
    for p in black_box(&pitches) {
        let _ = black_box(p.midi());
    }
    pitches
}

#[library_benchmark]
#[bench::batch(transpositions())]
fn transposed(input: ([Pitch; BATCH], [Interval; BATCH])) -> ([Pitch; BATCH], [Interval; BATCH]) {
    let (pitches, intervals) = &input;
    for (p, i) in black_box(pitches).iter().zip(black_box(intervals)) {
        let _ = black_box(p.transposed(*i));
    }
    input
}

#[library_benchmark]
#[bench::batch(pitches())]
fn interval_quality(pitches: [Pitch; BATCH]) -> [Pitch; BATCH] {
    // Consecutive pairs: 64 intervals (the last one wraps around to the first pitch).
    for (a, b) in black_box(&pitches)
        .iter()
        .zip(pitches.iter().cycle().skip(1))
    {
        let _ = black_box(a.interval_to(*b).and_then(Interval::quality));
    }
    pitches
}

#[library_benchmark]
#[bench::batch(midi_keys())]
fn spell_midi(input: [(u8, Key); BATCH]) -> [(u8, Key); BATCH] {
    for (k, key) in black_box(&input) {
        black_box(Pitch::spell_midi(*k, *key));
    }
    input
}

library_benchmark_group!(
    name = pitch,
    benchmarks = [midi, transposed, interval_quality, spell_midi]
);

main!(library_benchmark_groups = pitch);
