use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{
    Alteration, BaseValue, Command, Document, DynamicLevel, DynamicMark, DynamicPlacement, Editor,
    EventChange, EventId, MarkSpec, MeterMode, MoveMode, MovePlayed, NewBody, NewEvent, NoteId,
    NoteValue, Pitch, Placement, ScorePoint, Step,
};
use orchestra_core_time::{
    BarIndex, BarKind, Duration, IrregularBar, Meter, MeterChange, Rational,
};

#[path = "../tests/common/score.rs"]
mod score;

use score::Size;

const BATCH: usize = 64;

// The bars of a score.
fn bar_count(size: Size) -> u32 {
    match size {
        Size::Normal => 100,
        Size::Heavy => 1000,
    }
}

// An editor on the score of this size, with the editing instrument.
fn editor(size: Size) -> Editor {
    Editor::new(score::score(size, true))
}

// The editing voice (the last instrument's only voice).
fn editing_voice(doc: &Document) -> orchestra_core_model::VoiceId {
    doc.tracks().last().unwrap().instrument().voices()[0].id()
}

// A quarter note C5 entered into the editing voice at a bar and beat.
fn note(doc: &Document, bar: u32, beat: i64) -> Command {
    Command::EnterEvent(NewEvent {
        at: Placement::new(
            editing_voice(doc),
            doc.bars().id_at(BarIndex::new(bar)).unwrap(),
            Duration::from_rational(Rational::new(beat, 4).unwrap()),
        ),
        body: NewBody::Chord {
            value: NoteValue::plain(BaseValue::Quarter),
            pitches: vec![Pitch::new(Step::C, Alteration::NATURAL, 5)],
            grace: None,
        },
    })
}

// Where the i-th command of a batch goes: every 7th bar (7 is prime with 100 and 1 000, so the
// 64 bars of a batch are all different on both scores) and one of the first three beats, which
// every bar has (the scores have passages of 6/8, three quarters long).
fn spot(size: Size, i: usize) -> (u32, i64) {
    let i = u32::try_from(i).unwrap();
    ((i * 7) % bar_count(size), i64::from(i % 3))
}

// Checks, outside the measured region, that every command of a batch succeeds on a copy of the
// editor's document: a refused command would be measured as a (cheaper) refusal.
fn all_succeed(editor: &Editor, commands: &[Command]) {
    let mut copy = Editor::new(editor.document().clone());
    for command in commands {
        copy.execute(command).unwrap();
    }
}

// 64 notes spread over the score (see `spot`), with the editor.
fn notes(size: Size) -> (Editor, Vec<Command>) {
    let editor = editor(size);
    let doc = editor.document();
    let commands: Vec<Command> = (0..BATCH)
        .map(|i| {
            let (bar, beat) = spot(size, i);
            note(doc, bar, beat)
        })
        .collect();
    all_succeed(&editor, &commands);
    (editor, commands)
}

// 64 dynamics of the editing instrument, spread as the notes, with the editor.
fn dynamics(size: Size) -> (Editor, Vec<Command>) {
    let editor = editor(size);
    let doc = editor.document();
    let instrument = doc.tracks().last().unwrap().instrument();
    let (id, staff) = (instrument.id(), instrument.staves()[0].id());
    let commands: Vec<Command> = (0..BATCH)
        .map(|i| {
            let (bar, beat) = spot(size, i);
            let bar = doc.bars().id_at(BarIndex::new(bar)).unwrap();
            let offset = Duration::from_rational(Rational::new(beat, 4).unwrap());
            Command::AddMark(MarkSpec::Dynamic {
                instrument: id,
                at: ScorePoint::new(bar, offset),
                placement: DynamicPlacement::instrument(staff),
                mark: DynamicMark::Level(DynamicLevel::F),
            })
        })
        .collect();
    all_succeed(&editor, &commands);
    (editor, commands)
}

// An editor whose last step is a paste of 200 notes (four per bar, from bar 10).
fn pasted(size: Size) -> Editor {
    let mut editor = editor(size);
    let commands: Vec<Command> = (0..200_u32)
        .map(|i| note(editor.document(), 10 + i / 4, i64::from(i % 4)))
        .collect();
    editor
        .transact(|tx| commands.iter().try_for_each(|c| tx.execute(c)))
        .unwrap();
    assert_eq!(editor.undo_steps(), 1);
    editor
}

// An editor with one note in the editing voice in bar 10, and that note.
fn dragged(size: Size) -> (Editor, EventId) {
    let mut editor = editor(size);
    let command = note(editor.document(), 10, 0);
    editor.execute(&command).unwrap();
    let doc = editor.document();
    let bar = doc.bars().ids()[10];
    let event = doc.events(editing_voice(doc), bar).unwrap()[0].event().id();
    (editor, event)
}

#[library_benchmark]
#[bench::normal(notes(Size::Normal))]
#[bench::heavy(notes(Size::Heavy))]
fn enter_note(input: (Editor, Vec<Command>)) -> (Editor, Vec<Command>) {
    let (mut editor, commands) = input;
    for command in black_box(&commands) {
        let _ = black_box(editor.execute(command));
    }
    (editor, commands)
}

