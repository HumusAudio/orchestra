//! Instruction-count benchmarks of the editor: commands end to end, undo, bars, gestures
//! (ADR-0026 §8, SCALETTA F1.11b part 2b).
//!
//! # Why these operations
//! Everything one keystroke or one mouse movement can trigger must stay well under the 16 ms
//! re-layout budget of ADR-0007 on the heavy score; the target for entering a note is ≤ 1 ms
//! (ADR-0026 §8). Each benchmark runs the whole path: the command's checks, its edits with the
//! derived indices, the local check, the change set, the history step and, where it applies, the
//! tempo map derived again.
//!
//! - `enter_note`: a quarter note entered into free space, its own transaction (step input).
//! - `add_dynamic`: a dynamic added, its own transaction (the commonest mark command).
//! - `undo_paste`: the undo of a transaction of 200 notes (a paste).
//! - `insert_bar` and `delete_bar`: one bar in the middle of the score (O(bars × voices) pointer
//!   moves, the meter map, the tempo map; deletion also clips, carries and cascades).
//! - `change_meter` and `irregular_bar` (F1.11c, `KeepBars`): a 3/4 at the middle bar (on the
//!   heavy score its section lasts 60 bars, each now overfull, whose ties are checked: Y7), and
//!   the middle bar made a bar of two quarters.
//! - `rewrite_meter` (F1.11c part 2b): a 3/4 at the middle bar in `Rewrite` mode, which moves
//!   every event and mark of its section (60 bars on the heavy score) into the new bars.
//! - `gesture`: a drag of one note over 1 000 positions, from `begin_gesture` to `end_gesture`
//!   (each update is a command with its local check and its change set; the compaction keeps one
//!   old value).
//! - `daw_drag` (F1.14b, ADR-0028): a drag of the same note from the DAW view over 1 000
//!   positions, each a [`MovePlayed`](orchestra_core_model::MovePlayed) toward a target on a
//!   1/32 path inside its bar, asked from the note's current written start: half of the updates
//!   stay offsets (within the 1/32 threshold of the written place), the others move the written
//!   note on the 1/16 grid and keep the residual.
//!
//! # The scores
//! The normal and heavy scores of `tests/common/score.rs` (100 bars × 10 staves, 1 000 bars × 30
//! staves), with an empty editing instrument at the end where notes are entered into free space.
//!
//! # Batches and setup
//! The small commands run in batches of 64 (ADR-0017 §4), each command its own transaction;
//! divide by 64 for one. The large ones run once. The editor and the commands are built by the
//! argument expression, outside the measured region, and returned so that dropping them is not
//! measured either.

