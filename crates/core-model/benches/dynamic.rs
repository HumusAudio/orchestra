//! Instruction-count benchmarks of dynamics, hairpins and tempo marks (ADR-0024 §8 and §11,
//! SCALETTA F1.09c).
//!
//! # Why these operations
//! - `add_tempo_mark`: adding a tempo mark derives the whole tempo map again (ADR-0024 §11, the
//!   bulk edit of ADR-0022 §8); the commands of F1.11 will do the same after every edit of the
//!   marks or of where bars start, so this is the cost of one such edit. ADR-0024 estimated
//!   ≈ 0.6 ms for 250 segments from the F1.05b numbers; here 250 marks (half of them gradual,
//!   so ≈ 375 segments) over 1 000 bars, and the new mark goes near the start, where inserting
//!   shifts the most.
//! - `tempo_mark_in_force`: the tempo text in force at a point, which the interface shows next to
//!   the transport and the engraving asks at every system start.
//! - `validate_with_dynamics`: `validate` of a score with a dynamic and a hairpin in every bar of
//!   every instrument, so that rules 6 (hairpins) and 7 (tempo marks) are measured on top of the
//!   event rules. A name of its own (ADR-0017 §4): it measures a different score than the
//!   `validate` benchmarks of `benches/voice.rs` and `benches/marking.rs`.
//!
//! # Batches and setup
//! As in the other benchmark files: the lookup runs a batch of 64 (ADR-0017 §4); the builder or
//! document is prepared outside the measured region and returned so that dropping it is not
//! measured. `add_tempo_mark` is one edit per run, but an edit costs hundreds of thousands of
//! instructions, so one more or less of noise does not matter.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid constants; never part of the measured code"
)]
#![allow(
    clippy::large_types_passed_by_value,
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{
    Alteration, BarId, BaseValue, Clef, Document, DocumentBuilder, DynamicLevel, DynamicMark,
    DynamicPlacement, GradualMark, HairpinShape, Interval, Key, Metronome, Mode, NoteValue, Pitch,
    Placement, ScorePoint, Step, TempoMark, TempoMarkChange,
};
use orchestra_core_time::{BarIndex, Duration, Meter, MeterChange, MeterMap, Rational, Tempo};

// Lookups per batch (ADR-0017 §4).
const BATCH: usize = 64;

// The duration `n/d` of a whole note.
fn d(n: i64, den: i64) -> Duration {
    Duration::from_rational(Rational::new(n, den).unwrap())
}

// ♩ = `bpm`.
fn quarter(bpm: i64) -> Tempo {
    Tempo::new(d(1, 4), Rational::from_integer(bpm).unwrap()).unwrap()
}

// An empty builder in 4/4 at ♩ = 100 with `bars` bars.
fn builder(bars: usize) -> (DocumentBuilder, Vec<BarId>) {
    let meters = MeterMap::new(MeterChange::new(Meter::new(&[4], 4).unwrap())).unwrap();
    let mut b = DocumentBuilder::new(
        meters,
        TempoMark::immediate(Some("Allegro"), Metronome::shown(quarter(100))).unwrap(),
        Key::traditional(0, Mode::Major).unwrap(),
    )
    .unwrap();
    let ids = (0..bars).map(|_| b.add_bar().unwrap()).collect();
    (b, ids)
}

// 1 000 bars with a tempo mark every 4 bars from bar 4 (250 marks): a ritardando over two bars
// at the odd marks, "a tempo" at the even ones. Returns the builder, the point and the mark to
// add (an immediate change in bar 1, before every other mark).
fn tempo_marks() -> (DocumentBuilder, ScorePoint, TempoMark) {
    let (mut b, bars) = builder(1000);
    for (k, i) in (4..1000).step_by(4).enumerate() {
        let change = if k % 2 == 1 {
            TempoMarkChange::Gradual(GradualMark {
                from: None,
                to: quarter(72),
                end: ScorePoint::start_of(bars[i + 2]),
            })
        } else {
            TempoMarkChange::Immediate(Metronome::shown(quarter(100)))
        };
        b.add_tempo_mark(
            ScorePoint::start_of(bars[i]),
            TempoMark::new(None, Some(change)).unwrap(),
        )
        .unwrap();
    }
    let mark = TempoMark::immediate(Some("Più mosso"), Metronome::shown(quarter(120))).unwrap();
    (b, ScorePoint::new(bars[1], d(1, 2)), mark)
}

// The document of `tempo_marks` and 64 points spread over it, at the middle of a bar.
fn tempo_points() -> (Document, [(BarIndex, Duration); BATCH]) {
    let (b, _, _) = tempo_marks();
    let points = std::array::from_fn(|i| {
        let bar = u32::try_from((i * 157) % 1000).unwrap();
        (BarIndex::new(bar), d(1, 2))
    });
    (b.build().unwrap(), points)
}

// 200 bars and 10 one-staff instruments: four quarter notes per bar, a dynamic on every bar and
// a hairpin over its first three beats, crescendo and diminuendo in turn; a tempo mark every 8
// bars.
fn score() -> Document {
    let (mut b, bars) = builder(200);
    let unison = Interval::new(0, Rational::ZERO);
    let quarter_note = NoteValue::plain(BaseValue::Quarter);
    let pitch = Pitch::new(Step::G, Alteration::NATURAL, 4);
    let levels = [DynamicLevel::P, DynamicLevel::Mf, DynamicLevel::F];
    for _ in 0..10 {
        let track = b
            .add_instrument_track("Instrument", unison, &[Clef::TREBLE])
            .unwrap();
        let (instrument, staff, voice) = {
            let i = b.document().track(track).unwrap().instrument();
            (i.id(), i.staves()[0].id(), i.voices()[0].id())
        };
        let placement = DynamicPlacement::instrument(staff);
        for (i, &bar) in bars.iter().enumerate() {
            for beat in 0..4 {
                b.add_chord(
                    Placement::new(voice, bar, d(beat, 4)),
                    quarter_note,
                    &[pitch],
                )
                .unwrap();
            }
            b.add_dynamic(
                instrument,
                ScorePoint::start_of(bar),
                placement,
                DynamicMark::Level(levels[i % 3]),
            )
            .unwrap();
            let shape = if i % 2 == 0 {
                HairpinShape::CRESCENDO
            } else {
                HairpinShape::DIMINUENDO
            };
            b.add_hairpin(
                instrument,
                ScorePoint::start_of(bar),
                ScorePoint::new(bar, d(3, 4)),
                placement,
                shape,
            )
            .unwrap();
        }
    }
    for i in (8..200).step_by(8) {
        b.add_tempo_mark(
            ScorePoint::start_of(bars[i]),
            TempoMark::immediate(None, Metronome::hidden(quarter(90))).unwrap(),
        )
        .unwrap();
    }
    b.build().unwrap()
}

#[library_benchmark]
#[bench::near_the_start(tempo_marks())]
fn add_tempo_mark(input: (DocumentBuilder, ScorePoint, TempoMark)) -> DocumentBuilder {
    let (mut b, at, mark) = input;
    let _ = black_box(b.add_tempo_mark(black_box(at), mark));
    b
}

#[library_benchmark]
#[bench::batch(tempo_points())]
fn tempo_mark_in_force(
    input: (Document, [(BarIndex, Duration); BATCH]),
) -> (Document, [(BarIndex, Duration); BATCH]) {
    let (document, points) = &input;
    for &(bar, offset) in black_box(points) {
        let _ = black_box(
            document
                .tempo_marks()
                .in_force_at(document.bars(), bar, offset),
        );
    }
    input
}

#[library_benchmark]
#[bench::whole_score(score())]
fn validate_with_dynamics(input: Document) -> Document {
    let _ = black_box(black_box(&input).validate());
    input
}

library_benchmark_group!(
    name = dynamic,
    benchmarks = [add_tempo_mark, tempo_mark_in_force, validate_with_dynamics]
);

main!(library_benchmark_groups = dynamic);
