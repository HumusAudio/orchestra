//! Instruction-count benchmarks of the saved-document description (ADR-0029 S4, S12; SCALETTA
//! F1.15b part 1): the model's half of saving and opening a project file.
//!
//! - `to_parts`: the description of a whole document (one copy of all its saved data), what a
//!   save starts from.
//! - `from_parts`: a document built back from its description: the replay through the builder
//!   with the saved IDs, the full `validate`, and the comparison of the rebuilt description with
//!   the given one (ADR-0029 S8). What an opening ends with, after the file has been parsed.
//!
//! The budget of ADR-0007 is the opening of 100 bars in ≤ 1 s on the reference laptop, the file's
//! parsing included (crate `io`, F1.15b part 2): the normal score must stay far below it. The heavy
//! score (1 000 bars × 30 staves) shows how the cost grows.
//!
//! # The scores
//! The normal and heavy plain scores of `orchestra-test-scores` (ADR-0031). Each benchmark runs once on the whole
//! score (an operation of millions of instructions needs no batch, ADR-0017 §4); the input is
//! prepared outside the measured region and returned, so that dropping it is not measured.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid inputs; never part of the measured code"
)]
#![allow(
    clippy::large_types_passed_by_value,
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{Document, DocumentParts};

// The plain preset of the reference scores (ADR-0031): `plain(size, instruments)`.
use orchestra_test_scores::{Instruments, Size, plain};

// The document of this size.
fn document(size: Size) -> Document {
    plain(size, Instruments::Plain)
}

// The description of the document of this size.
fn description(size: Size) -> DocumentParts {
    plain(size, Instruments::Plain).to_parts()
}

#[library_benchmark]
#[bench::normal(document(Size::Normal))]
#[bench::heavy(document(Size::Heavy))]
fn to_parts(doc: Document) -> (Document, DocumentParts) {
    let parts = black_box(&doc).to_parts();
    (doc, black_box(parts))
}

#[library_benchmark]
#[bench::normal(description(Size::Normal))]
#[bench::heavy(description(Size::Heavy))]
fn from_parts(parts: DocumentParts) -> (DocumentParts, Document) {
    let doc = Document::from_parts(black_box(&parts)).unwrap();
    (parts, black_box(doc))
}

library_benchmark_group!(name = parts, benchmarks = [to_parts, from_parts]);

main!(library_benchmark_groups = parts);
