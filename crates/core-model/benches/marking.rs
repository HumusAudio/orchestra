//! Instruction-count benchmarks of the markings, slurs and score order (ADR-0024 §5–§7, SCALETTA
//! F1.09c).
//!
//! # Why these operations
//! - `slurs_at`: the engraving asks it for every event it draws (which slurs start or end here),
//!   and the commands of F1.11 when an event is deleted; it is one lookup in the derived index.
//! - `slur_by_id`: selecting or editing a slur finds it through its instrument's sorted table.
//! - `comes_before`: the score order of two events, which `validate` asks for every tie and slur,
//!   and the commands will ask when a slur or tie is drawn by the user.
//! - `validate`: run once per document built (file opening), now with the grace rule and the
//!   slur rule; it is part of the "open a 100-bar score in ≤ 1 s" budget of ADR-0007. It has its
//!   own name here (`validate_with_markings`) because it measures a different score than the
//!   `validate` of `benches/voice.rs` (ADR-0017: a new name when the meaning changes).
//!
//! # The document
//! 200 bars of 4/4 and 10 one-staff instruments with one voice each. Every bar of every voice
//! holds an acciaccatura before its first beat, four quarter notes with an accent and a mordent,
//! and an After grace at the barline: 6 events per voice and bar, 12 000 events in all. Every bar
//! has two slurs (grace → first note, first → last note) and every 4 bars a phrase mark from the
//! first note of the first bar to the last note of the fourth: 4 500 slurs in all, and the first
//! note of every fourth bar is touched by three slurs (the "many" case of the index).
//!
//! # Batches and setup
//! As in `benches/voice.rs`: each lookup benchmark runs a batch of 64 (ADR-0017 §4); the document
//! is built outside the measured region and returned so that dropping it is not measured.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid constants; never part of the measured code"
)]
#![allow(
    clippy::large_types_passed_by_value,
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{
    Alteration, Articulation, ArticulationSet, BarId, BaseValue, Clef, Document, DocumentBuilder,
    EventId, Grace, GraceAttach, GraceKind, Interval, Key, Metronome, Mode, NoteValue, Ornament,
    Pitch, Placement, SlurId, SlurPlacement, Step, TempoMark,
};
use orchestra_core_time::{Duration, Meter, MeterChange, MeterMap, Rational, Tempo};

const BATCH: usize = 64;
const BARS: usize = 200;
const INSTRUMENTS: usize = 10;

fn d(n: i64, den: i64) -> Duration {
    Duration::from_rational(Rational::new(n, den).unwrap())
}

// The document described in the module comment, with its events in score order (per voice) and
// its slurs in creation order.
fn score() -> (Document, Vec<EventId>, Vec<SlurId>) {
    let meters = MeterMap::new(MeterChange::new(Meter::new(&[4], 4).unwrap())).unwrap();
    let tempo = Tempo::new(d(1, 4), Rational::from_integer(100).unwrap()).unwrap();
    let key = Key::traditional(0, Mode::Major).unwrap();
    let mut b = DocumentBuilder::new(
        meters,
        TempoMark::immediate(None, Metronome::shown(tempo)).unwrap(),
        key,
    )
    .unwrap();
    let bars: Vec<BarId> = (0..BARS).map(|_| b.add_bar().unwrap()).collect();
    let unison = Interval::new(0, Rational::ZERO);
    let pitch = Pitch::new(Step::A, Alteration::NATURAL, 4);
    let quarter = NoteValue::plain(BaseValue::Quarter);
    let eighth = NoteValue::plain(BaseValue::Eighth);
    let accent = ArticulationSet::EMPTY.with(Articulation::Accent);
    let grace = |attach| Grace {
        kind: GraceKind::Acciaccatura,
        attach,
    };
    let (mut events, mut slurs) = (Vec::new(), Vec::new());
    for _ in 0..INSTRUMENTS {
        let track = b
            .add_instrument_track("I", unison, &[Clef::TREBLE])
            .unwrap();
        let voice = b.document().track(track).unwrap().instrument().voices()[0].id();
        let mut phrase_start = None;
        for (n, &bar) in bars.iter().enumerate() {
            let before = b
                .add_grace_chord(
                    Placement::new(voice, bar, Duration::ZERO),
                    grace(GraceAttach::Before),
                    eighth,
                    &[pitch],
                )
                .unwrap()
                .event;
            let notes: Vec<EventId> = (0..4)
                .map(|beat| {
                    let at = Placement::new(voice, bar, d(beat, 4));
                    let id = b.add_chord(at, quarter, &[pitch]).unwrap().event;
                    b.set_articulations(id, accent).unwrap();
                    b.set_ornament(id, Some(Ornament::Mordent)).unwrap();
                    id
                })
                .collect();
            let after = b
                .add_grace_chord(
                    Placement::new(voice, bar, d(1, 1)),
                    grace(GraceAttach::After),
                    eighth,
                    &[pitch],
                )
                .unwrap()
                .event;
            slurs.push(b.add_slur(before, notes[0], SlurPlacement::Auto).unwrap());
            slurs.push(
                b.add_slur(notes[0], notes[3], SlurPlacement::Above)
                    .unwrap(),
            );
            if n % 4 == 0 {
                phrase_start = Some(notes[0]);
            }
            if n % 4 == 3
                && let Some(start) = phrase_start.take()
            {
                slurs.push(b.add_slur(start, notes[3], SlurPlacement::Above).unwrap());
            }
            events.push(before);
            events.extend(notes);
            events.push(after);
        }
    }
    (b.build().unwrap(), events, slurs)
}

// 64 events spread over the score (every 151st: graces, first notes touched by three slurs,
// notes touched by none).
fn events() -> (Document, [EventId; BATCH]) {
    let (document, all, _) = score();
    let ids = std::array::from_fn(|i| all[(i * 151) % all.len()]);
    (document, ids)
}

// 64 pairs of consecutive events of one voice, spread over the score: graces and their main
// notes (same position, the slot decides) and notes on successive beats.
fn pairs() -> (Document, [(EventId, EventId); BATCH]) {
    let (document, all, _) = score();
    let pairs = std::array::from_fn(|i| {
        // Never the last event of a voice, so that the pair stays in one voice.
        let k = (i * 151) % (all.len() - 1);
        (all[k], all[k + 1])
    });
    (document, pairs)
}

// 64 slurs spread over the score.
fn slur_ids() -> (Document, [SlurId; BATCH]) {
    let (document, _, all) = score();
    let ids = std::array::from_fn(|i| all[(i * 67) % all.len()]);
    (document, ids)
}

#[library_benchmark]
#[bench::batch(events())]
fn slurs_at(input: (Document, [EventId; BATCH])) -> (Document, [EventId; BATCH]) {
    let (document, ids) = &input;
    for id in black_box(ids) {
        let _ = black_box(document.slurs_at(*id));
    }
    input
}

#[library_benchmark]
#[bench::batch(slur_ids())]
fn slur_by_id(input: (Document, [SlurId; BATCH])) -> (Document, [SlurId; BATCH]) {
    let (document, ids) = &input;
    for id in black_box(ids) {
        let _ = black_box(document.slur(*id));
    }
    input
}

#[library_benchmark]
#[bench::batch(pairs())]
fn comes_before(
    input: (Document, [(EventId, EventId); BATCH]),
) -> (Document, [(EventId, EventId); BATCH]) {
    let (document, pairs) = &input;
    for &(a, z) in black_box(pairs) {
        let _ = black_box(document.comes_before(a, z));
    }
    input
}

#[library_benchmark]
#[bench::whole_score(score().0)]
fn validate_with_markings(input: Document) -> Document {
    let _ = black_box(black_box(&input).validate());
    input
}

library_benchmark_group!(
    name = marking,
    benchmarks = [slurs_at, slur_by_id, comes_before, validate_with_markings]
);

main!(library_benchmark_groups = marking);
