//! Instruction-count benchmarks of the document skeleton's lookups (ADR-0022, SCALETTA F1.08).
//!
//! # Why these operations
//! From F1.09 on, every event is stored as (bar, offset) under its voice: the layout, the playback
//! compile and the commands turn a `BarId` into its index and its start position, and find a
//! voice (with its instrument) by ID, once per event or per bar edited. These lookups run on the
//! heavy score of ADR-0022 (1 000 bars, 30 staves), so their cost is measured on a skeleton of that
//! size: 1 000 bars, 20 instruments with 30 staves and 40 voices in all.
//!
//! # Batches and setup
//! Each benchmark runs its lookup on a batch of 64 inputs (ADR-0017 §4: a single call is too
//! small and drifts by an instruction when unrelated code changes); divide by 64 for one call. The
//! document and the inputs are built by the argument expression, which Gungraun evaluates outside
//! the measured region, and they are returned so that dropping them is not measured either.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
// The setup functions build inputs from constants known to be valid: a failure there is a bug of
// the benchmark itself and should stop it loudly.
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid constants; never part of the measured code"
)]
// Gungraun moves each benchmark's input into the function (so that building it is not measured).
#![allow(
    clippy::large_types_passed_by_value,
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{
    BarId, Clef, Document, DocumentBuilder, Interval, Key, Metronome, Mode, TempoMark, Voice,
    VoiceId,
};
use orchestra_core_time::{BarIndex, Duration, Meter, MeterChange, MeterMap, Rational, Tempo};

/// `n` treble clefs: the initial clefs of an instrument with `n` staves (the skeleton tests do not
/// care which clef each staff starts with, only how many staves there are).
fn clefs(n: usize) -> Vec<Clef> {
    vec![Clef::TREBLE; n]
}

/// C major: the initial key of every test document.
fn c_major() -> Key {
    Key::traditional(0, Mode::Major).unwrap()
}

const BATCH: usize = 64;
const BARS: usize = 1000;

// The heavy skeleton: 1 000 bars in 4/4 with a meter change every 50 bars (so that the meter map
// lookup inside `bar_start` searches among 20 segments), 10 one-staff instruments, 10 two-staff
// instruments each with an extra voice: 30 staves, 40 voices.
fn skeleton() -> Document {
    let mut meters = MeterMap::new(MeterChange::new(Meter::new(&[4], 4).unwrap())).unwrap();
    for i in 1..20_u32 {
        let meter = if i % 2 == 0 {
            Meter::new(&[4], 4)
        } else {
            Meter::new(&[3], 4)
        };
        meters
            .set_meter_change(BarIndex::new(i * 50), MeterChange::new(meter.unwrap()))
            .unwrap();
    }
    let quarter = Duration::from_rational(Rational::new(1, 4).unwrap());
    let tempo = Tempo::new(quarter, Rational::from_integer(100).unwrap()).unwrap();
    let mut b = DocumentBuilder::new(
        meters,
        TempoMark::immediate(None, Metronome::shown(tempo)).unwrap(),
        c_major(),
    )
    .unwrap();
    for _ in 0..BARS {
        b.add_bar().unwrap();
    }
    let unison = Interval::new(0, Rational::ZERO);
    for i in 0..20 {
        let staves = if i < 10 { 1 } else { 2 };
        let track = b.add_instrument_track("I", unison, &clefs(staves)).unwrap();
        if staves == 2 {
            let staff = b.document().track(track).unwrap().instrument().staves()[0].id();
            b.add_voice(staff).unwrap();
        }
    }
    b.build().unwrap()
}

// 64 bars spread over the whole score (every 15th bar), with the document.
fn bars() -> (Document, [BarId; BATCH]) {
    let document = skeleton();
    let ids = std::array::from_fn(|i| document.bars().ids()[(i * 15) % BARS]);
    (document, ids)
}

// 64 voices cycling over all 40, so that the linear scans are measured on average and at the end.
fn voices() -> (Document, [VoiceId; BATCH]) {
    let document = skeleton();
    let all: Vec<VoiceId> = document
        .tracks()
        .iter()
        .flat_map(|t| t.instrument().voices().iter().map(Voice::id))
        .collect();
    let ids = std::array::from_fn(|i| all[(i * 7) % all.len()]);
    (document, ids)
}

#[library_benchmark]
#[bench::batch(bars())]
fn bar_index_of(input: (Document, [BarId; BATCH])) -> (Document, [BarId; BATCH]) {
    let (document, ids) = &input;
    for id in black_box(ids) {
        let _ = black_box(document.bars().index_of(*id));
    }
    input
}

#[library_benchmark]
#[bench::batch(bars())]
fn bar_start(input: (Document, [BarId; BATCH])) -> (Document, [BarId; BATCH]) {
    let (document, ids) = &input;
    for id in black_box(ids) {
        let _ = black_box(document.bar_start(*id));
    }
    input
}

#[library_benchmark]
#[bench::batch(voices())]
fn voice_lookup(input: (Document, [VoiceId; BATCH])) -> (Document, [VoiceId; BATCH]) {
    let (document, ids) = &input;
    for id in black_box(ids) {
        let _ = black_box(document.voice(*id));
    }
    input
}

library_benchmark_group!(
    name = document,
    benchmarks = [bar_index_of, bar_start, voice_lookup]
);

main!(library_benchmark_groups = document);
