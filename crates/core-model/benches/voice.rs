//! Instruction-count benchmarks of the voices' content (ADR-0024, SCALETTA F1.09b).
//!
//! # Why these operations
//! - `metric_duration` (through the voice, and by event ID): the layout and the playback compile
//!   compute the duration of every event they read; inside nested tuplets it walks the chain of
//!   ratios.
//! - `event_lookup`: finding an event by ID (selection, commands, ties) goes through the derived
//!   index, the voice scan and the chunk scan of ADR-0022 §1.
//! - `clef_at` and `written_key_at`: asked once per event by the engraving (which staff line a
//!   pitch sits on, which accidentals the key implies) and by the DAW's spelling.
//! - `validate`: run once per document built (file opening): its cost is part of the "open a
//!   100-bar score in ≤ 1 s" budget of ADR-0007.
//!
//! # The document
//! 200 bars of 4/4 and 10 one-staff instruments with one voice each. Every bar of every voice
//! holds a quarter-note triplet (three chords of 1/6, inside a 3:2 tuplet) and then two quarter
//! chords of two noteheads: 5 events per voice and bar, 10 000 events in all, every bar exactly
//! full. Every staff has a clef change every 10 bars, the score a key change every 20 bars.
//!
//! # Batches and setup
//! As in `benches/document.rs`: each lookup benchmark runs a batch of 64 (ADR-0017 §4); the
//! document is built outside the measured region and returned so that dropping it is not measured.

