use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{
    Alteration, BarId, BaseValue, Clef, Document, DocumentBuilder, EventId, InstrumentId, Interval,
    Key, Metronome, Mode, NoteValue, Pitch, Placement, StaffId, Step, TempoMark, Tuplet,
};
use orchestra_core_time::{BarIndex, Duration, Meter, MeterChange, MeterMap, Rational, Tempo};

#[path = "../tests/common/duration.rs"]
mod duration;
use duration::d;

const BATCH: usize = 64;
const BARS: usize = 200;
const INSTRUMENTS: usize = 10;

// The document described in the module comment.
fn score() -> Document {
    let meters = MeterMap::new(MeterChange::new(Meter::new(&[4], 4).unwrap())).unwrap();
    let tempo = Tempo::new(d(1, 4), Rational::from_integer(100).unwrap()).unwrap();
    let key = |fifths| Key::traditional(fifths, Mode::Major).unwrap();
    let mut b = DocumentBuilder::new(
        meters,
        TempoMark::immediate(None, Metronome::shown(tempo)).unwrap(),
        key(0),
    )
    .unwrap();
    let bars: Vec<BarId> = (0..BARS).map(|_| b.add_bar().unwrap()).collect();
    for i in 1..BARS / 20 {
        let fifths = i8::try_from(i % 7).unwrap() - 3;
        b.add_key_change(bars[i * 20], Duration::ZERO, key(fifths))
            .unwrap();
    }
    let unison = Interval::new(0, Rational::ZERO);
    let c4 = Pitch::new(Step::C, Alteration::NATURAL, 4);
    let g4 = Pitch::new(Step::G, Alteration::NATURAL, 4);
    for _ in 0..INSTRUMENTS {
        let track = b
            .add_instrument_track("I", unison, &[Clef::TREBLE])
            .unwrap();
        let (voice, staff) = {
            let i = b.document().track(track).unwrap().instrument();
            (i.voices()[0].id(), i.staves()[0].id())
        };
        for (n, &bar) in bars.iter().enumerate() {
            if n % 10 == 5 {
                let clef = if n % 20 == 5 {
                    Clef::BASS
                } else {
                    Clef::TREBLE
                };
                b.add_clef_change(staff, bar, d(1, 2), clef).unwrap();
            }
            let triplet = b
                .add_tuplet(
                    voice,
                    Tuplet::new(3, 2, NoteValue::plain(BaseValue::Quarter)).unwrap(),
                    None,
                )
                .unwrap();
            for i in 0..3 {
                let at = Placement::new(voice, bar, d(i, 6)).in_tuplet(triplet);
                b.add_chord(at, NoteValue::plain(BaseValue::Quarter), &[c4])
                    .unwrap();
            }
            for i in 2..4 {
                let at = Placement::new(voice, bar, d(i, 4));
                b.add_chord(at, NoteValue::plain(BaseValue::Quarter), &[c4, g4])
                    .unwrap();
            }
        }
    }
    b.build().unwrap()
}

// Every event of the score, in track, voice and bar order.
fn all_events(document: &Document) -> Vec<EventId> {
    let mut ids = Vec::new();
    for track in document.tracks() {
        for voice in track.instrument().voices() {
            for &bar in document.bars().ids() {
                for e in document.events(voice.id(), bar).unwrap() {
                    ids.push(e.event().id());
                }
            }
        }
    }
    ids
}

// 64 events spread over the score (every 151st: all voices, bars and tuplet members).
fn events() -> (Document, [EventId; BATCH]) {
    let document = score();
    let all = all_events(&document);
    let ids = std::array::from_fn(|i| all[(i * 151) % all.len()]);
    (document, ids)
}

// 64 (staff, bar) points spread over the score.
fn staff_points() -> (Document, [(StaffId, BarId); BATCH]) {
    let document = score();
    let staves: Vec<StaffId> = document
        .tracks()
        .iter()
        .map(|t| t.instrument().staves()[0].id())
        .collect();
    let bars = document.bars().ids().to_vec();
    let points = std::array::from_fn(|i| (staves[i % staves.len()], bars[(i * 37) % bars.len()]));
    (document, points)
}

// 64 (instrument, bar) points spread over the score.
fn instrument_points() -> (Document, [(InstrumentId, BarId); BATCH]) {
    let document = score();
    let instruments: Vec<InstrumentId> = document
        .tracks()
        .iter()
        .map(|t| t.instrument().id())
        .collect();
    let bars = document.bars().ids().to_vec();
    let points = std::array::from_fn(|i| {
        (
            instruments[i % instruments.len()],
            bars[(i * 37) % bars.len()],
        )
    });
    (document, points)
}

// The first voice of the score and 13 consecutive bars (65 events), walked as the layout of
// one system walks them: bar by bar, chunk by chunk, asking each event's duration.
fn walk() -> (Document, Vec<BarIndex>) {
    let document = score();
    let bars = (40..53).map(BarIndex::new).collect();
    (document, bars)
}

#[library_benchmark]
#[bench::system(walk())]
fn voice_metric_duration(input: (Document, Vec<BarIndex>)) -> (Document, Vec<BarIndex>) {
    let (document, bars) = &input;
    let voice = &document.tracks()[0].instrument().voices()[0];
    let whole = Duration::from_rational(Rational::ONE);
    for &bar in black_box(bars) {
        for placed in voice.events_at(bar) {
            let _ = black_box(voice.metric_duration(black_box(placed.event()), whole));
        }
    }
    input
}

#[library_benchmark]
#[bench::batch(events())]
fn metric_duration_by_id(input: (Document, [EventId; BATCH])) -> (Document, [EventId; BATCH]) {
    let (document, ids) = &input;
    for id in black_box(ids) {
        let _ = black_box(document.metric_duration(*id));
    }
    input
}

#[library_benchmark]
#[bench::batch(events())]
fn event_lookup(input: (Document, [EventId; BATCH])) -> (Document, [EventId; BATCH]) {
    let (document, ids) = &input;
    for id in black_box(ids) {
        let _ = black_box(document.event(*id));
    }
    input
}

#[library_benchmark]
#[bench::batch(staff_points())]
fn clef_at(input: (Document, [(StaffId, BarId); BATCH])) -> (Document, [(StaffId, BarId); BATCH]) {
    let (document, points) = &input;
    let offset = Duration::from_rational(Rational::new(3, 4).unwrap());
    for &(staff, bar) in black_box(points) {
        let _ = black_box(document.clef_at(staff, bar, offset));
    }
    input
}

#[library_benchmark]
#[bench::batch(instrument_points())]
fn written_key_at(
    input: (Document, [(InstrumentId, BarId); BATCH]),
) -> (Document, [(InstrumentId, BarId); BATCH]) {
    let (document, points) = &input;
    for &(instrument, bar) in black_box(points) {
        let _ = black_box(document.written_key_at(instrument, bar, Duration::ZERO));
    }
    input
}

#[library_benchmark]
#[bench::whole_score(score())]
fn validate(input: Document) -> Document {
    let _ = black_box(black_box(&input).validate());
    input
}

library_benchmark_group!(
    name = voice,
    benchmarks = [
        voice_metric_duration,
        metric_duration_by_id,
        event_lookup,
        clef_at,
        written_key_at,
        validate
    ]
);

main!(library_benchmark_groups = voice);
