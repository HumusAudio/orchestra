//! Instruction-count benchmarks of the form, first part (ADR-0025 §2–§3, SCALETTA F1.10b).
//!
//! # Why these operations
//! - `bar_label_continue` and `bar_label_lettered`: the number shown above a bar, which layout
//!   asks at every system start and the DAW's bar ruler for every bar it draws. With `Continue`
//!   it is the plain number of `core-time`; with the lettered style it walks the volta groups
//!   before the bar (O(v + b)), so the second benchmark measures the worst realistic case, bars
//!   near the end of a score with many groups.
//! - `validate_with_form`: `validate` of a score whose cost is mostly rules 8 and 9 (no events),
//!   part of the "open a score in ≤ 1 s" budget of ADR-0007.
//!
//! # The document
//! 400 bars in 50 sections of 8: a start repeat, five bars, a "1. :‖ 2. :‖ 3." group of one-bar
//! voltas: 50 starts, 100 ends, 150 voltas, far more than a real score.
//!
//! # Batches and setup
//! Each lookup benchmark runs a batch of 64 (ADR-0017 §4); the document is built outside the
//! measured region and returned so that dropping it is not measured.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid constants; never part of the measured code"
)]
#![allow(
    clippy::large_types_passed_by_value,
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{
    BarId, BarNumbering, Document, DocumentBuilder, Key, Metronome, Mode, PassSet, TempoMark,
};
use orchestra_core_time::{Duration, Meter, MeterChange, MeterMap, Rational, Tempo};

// Lookups per batch (ADR-0017 §4).
const BATCH: usize = 64;

// Bars of the document.
const BARS: usize = 400;

// The document described in the module comment, in the given numbering style, with its bars.
fn score(style: BarNumbering) -> (Document, Vec<BarId>) {
    let meters = MeterMap::new(MeterChange::new(Meter::new(&[4], 4).unwrap())).unwrap();
    let tempo = Tempo::new(
        Duration::from_rational(Rational::new(1, 4).unwrap()),
        Rational::from_integer(100).unwrap(),
    )
    .unwrap();
    let mut b = DocumentBuilder::new(
        meters,
        TempoMark::immediate(None, Metronome::shown(tempo)).unwrap(),
        Key::traditional(0, Mode::Major).unwrap(),
    )
    .unwrap();
    let bars: Vec<BarId> = (0..BARS).map(|_| b.add_bar().unwrap()).collect();
    for section in (0..BARS).step_by(8) {
        b.add_repeat_start(bars[section]).unwrap();
        for (k, at) in (section + 5..section + 8).enumerate() {
            let pass = u8::try_from(k + 1).unwrap();
            b.add_volta(
                bars[at],
                bars[at],
                PassSet::range(pass, pass).unwrap(),
                k < 2,
                None,
            )
            .unwrap();
            if k < 2 {
                b.add_repeat_end(bars[at], 3).unwrap();
            }
        }
    }
    b.set_bar_numbering(style);
    (b.build().unwrap(), bars)
}

// 64 bars spread over the second half of the score (the lettered style walks the groups before
// them).
fn points(style: BarNumbering) -> (Document, [BarId; BATCH]) {
    let (document, bars) = score(style);
    let ids = std::array::from_fn(|i| bars[BARS / 2 + (i * 3) % (BARS / 2)]);
    (document, ids)
}

#[library_benchmark]
#[bench::batch(points(BarNumbering::Continue))]
fn bar_label_continue(input: (Document, [BarId; BATCH])) -> (Document, [BarId; BATCH]) {
    let (document, ids) = &input;
    for &id in black_box(ids) {
        let _ = black_box(document.bar_label(id));
    }
    input
}

#[library_benchmark]
#[bench::batch(points(BarNumbering::SameAsFirstLettered))]
fn bar_label_lettered(input: (Document, [BarId; BATCH])) -> (Document, [BarId; BATCH]) {
    let (document, ids) = &input;
    for &id in black_box(ids) {
        let _ = black_box(document.bar_label(id));
    }
    input
}

#[library_benchmark]
#[bench::whole_score(score(BarNumbering::Continue).0)]
fn validate_with_form(input: Document) -> Document {
    let _ = black_box(black_box(&input).validate());
    input
}

library_benchmark_group!(
    name = form,
    benchmarks = [bar_label_continue, bar_label_lettered, validate_with_form]
);

main!(library_benchmark_groups = form);
