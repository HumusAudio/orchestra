//! The **phase benchmarks** of Phase 1 (SCALETTA F1.16c): whole paths the user waits for, measured
//! end to end on the full preset of the reference scores (ADR-0031 §6), in instructions (ADR-0016,
//! ADR-0017).
//!
//! # Why here and not in the crates that own the code
//! Each crate already measures its own operations in isolation (`io`'s loading, `playback`'s
//! update, `core-model`'s commands). A phase benchmark crosses three crates (`io`, `core-model`,
//! `playback`): it lives in the test-only crate of the reference scores, which may depend on all of
//! them as dev-dependencies without adding any edge to the real dependency graph (owner's choice,
//! 2026-11-07).
//!
//! # What is measured
//! - `open`: from the file's bytes to a score ready to play: `from_bytes` (JSON, conversion,
//!   replay through the builder, `validate`), then the unrolled path (`Unrolled::new`), then the
//!   played notes (`Performance::new`). The disk is left out: what it adds depends on the machine.
//!   Budget (ADR-0007): ≤ 1 s for 100 bars.
//! - `edit_pitch`: the edit from the notation: one note of the repeat of section A (played twice)
//!   goes up a step. The command through the editor (with its undo step and change set), the
//!   path's update, the played notes' update. Budget: from input to frame ≤ 50 ms, of which the
//!   model's part should be a small fraction (the layout and the drawing come in Phase 2).
//! - `edit_daw`: the edit from the DAW: the same kind of note dragged by a 64th note, within the
//!   tolerance threshold (1/32 by default, ADR-0028), so it stays a performance offset and the
//!   score does not change. Same three steps, same budget.
//! - `unroll` (normal only): the path alone, as rebuilt after every change of the form or the
//!   bars.
//! - `save` (normal only): the file's bytes (`to_bytes`).
//!
//! # From instructions to time
//! The rule approved by the owner on 2026-11-07: **one instruction per nanosecond** on the
//! reference laptop (ADR-0007), i.e. one billion per second. It is deliberately pessimistic (a core
//! of that class retires two to four instructions per nanosecond on this kind of code), so a count
//! far below a budget by this rule is safely below it in reality; a count near a budget is a
//! warning to look closer. The real times are measured on the laptop in SCALETTA F2.23.
//!
//! # Sizes (owner's choice, 2026-11-07)
//! Normal (100 bars × 10 staves) for every benchmark; heavy (1 000 bars × 30 staves) only for
//! `open` and the two edits, to keep the CI job short: Gungraun runs the setup under Valgrind too,
//! so every heavy variant costs its generation even though only the measured part is counted.
//!
//! # Setup
//! Every input is built by the argument expression, outside the measured region, and returned by
//! the benchmark, so that dropping it is not measured either. The setup of an edit checks what the
//! benchmark relies on: the note is in a bar played twice, the command succeeds, and the DAW move
//! leaves the written position unchanged; otherwise a refusal or another path could be measured by
//! mistake.

