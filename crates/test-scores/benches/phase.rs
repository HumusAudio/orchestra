use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{
    BarId, ChangeSet, Command, Document, Editor, EventChange, MoveMode, MovePlayed, NoteId, Pitch,
    Step,
};
use orchestra_core_time::{BarIndex, Duration, Rational};
use orchestra_playback::{Performance, Unrolled};
use orchestra_test_scores::{Size, full};

// The two kinds of edit measured.
#[derive(Clone, Copy)]
enum Edit {
    // A note goes up a step (from the notation).
    Pitch,
    // A note is dragged by a 64th, within the threshold (from the DAW).
    Daw,
}

// The duration `n/den` of a whole note.
fn d(n: i64, den: i64) -> Duration {
    Duration::from_rational(Rational::new(n, den).unwrap())
}

// The file's bytes of the full score of this size.
fn bytes(size: Size) -> Vec<u8> {
    orchestra_io::to_bytes(&full(size)).unwrap()
}

// The full score of this size.
fn document(size: Size) -> Document {
    full(size)
}

// The pitch one diatonic step above `pitch`, with the same alteration (B goes to the C of the next
// octave).
fn step_up(pitch: Pitch) -> Pitch {
    let (step, octave) = match pitch.step() {
        Step::C => (Step::D, pitch.octave()),
        Step::D => (Step::E, pitch.octave()),
        Step::E => (Step::F, pitch.octave()),
        Step::F => (Step::G, pitch.octave()),
        Step::G => (Step::A, pitch.octave()),
        Step::A => (Step::B, pitch.octave()),
        Step::B => (Step::C, pitch.octave() + 1),
    };
    Pitch::new(step, pitch.alteration(), octave)
}

// The command of `edit` on `note`.
fn command(edit: Edit, doc: &Document, note: NoteId) -> Command {
    match edit {
        Edit::Pitch => {
            let (event, head) = doc.note(note).unwrap();
            Command::ChangeEvent {
                event: event.event().id(),
                change: EventChange::Pitch {
                    note,
                    pitch: step_up(head.pitch()),
                },
            }
        }
        Edit::Daw => Command::MovePlayed(MovePlayed {
            note,
            pass: None,
            onset: d(1, 64),
            grid: d(1, 16),
            mode: MoveMode::ByThreshold,
        }),
    }
}

// The single notes in bars 1–15 of the first movement (the body of the repeat of section A,
// played twice), in a fixed order, so the benchmark always measures the same note: first violin I
// (a melody instrument of both ensembles that rarely rests, so the normal and heavy variants edit
// the same kind of note and their counts compare), then every other voice in track order, as a
// fallback in case it rests through both phrases (the tacets of `full::music`).
fn candidates(doc: &Document) -> Vec<(BarId, NoteId)> {
    let instruments = doc
        .tracks()
        .iter()
        .map(orchestra_core_model::Track::instrument);
    let (first, others): (Vec<_>, Vec<_>) = instruments.partition(|i| i.name() == "Violin I");
    let mut notes = Vec::new();
    for voice in first
        .into_iter()
        .chain(others)
        .flat_map(orchestra_core_model::Instrument::voices)
    {
        for index in 1..=15 {
            let bar = doc.bars().id_at(BarIndex::new(index)).unwrap();
            for placed in doc.events(voice.id(), bar).unwrap() {
                let event = placed.event();
                if let Some(chord) = event.chord()
                    && event.grace().is_none()
                    && chord.len() == 1
                {
                    notes.push((bar, chord.notes().next().unwrap().id()));
                }
            }
        }
    }
    notes
}

// The input of an edit benchmark: an editor on the full score of this size, the path and the
// played notes before the edit, and the command. The first candidate note on which the command
// succeeds is used (a note that is the target of a tie cannot be dragged from the DAW, which keys
// a played note by the first notehead of its chain); the checks are those of the module
// documentation.
fn edit_input(size: Size, edit: Edit) -> (Editor, Unrolled, Performance, Command) {
    let doc = full(size);
    let path = Unrolled::new(&doc).unwrap();
    for (bar, note) in candidates(&doc) {
        let index = doc.bars().ids().iter().position(|&b| b == bar).unwrap();
        assert_eq!(
            path.plays_of(BarIndex::new(u32::try_from(index).unwrap()))
                .len(),
            2
        );
        let command = command(edit, &doc, note);
        let mut trial = Editor::new(doc.clone());
        if trial.execute(&command).is_err() {
            continue;
        }
        if matches!(edit, Edit::Daw) {
            // Within the threshold: the written position is unchanged.
            let before = doc.note(note).unwrap().0.offset();
            let after = trial.document().note(note).unwrap().0.offset();
            assert_eq!(before, after, "the DAW move became a written move");
        }
        let performance = Performance::new(&doc, &path).unwrap();
        return (Editor::new(doc), path, performance, command);
    }
    panic!("no note of the repeat accepts the edit");
}

// From the file's bytes to a score ready to play.
#[library_benchmark]
#[bench::normal(bytes(Size::Normal))]
#[bench::heavy(bytes(Size::Heavy))]
fn open(bytes: Vec<u8>) -> (Vec<u8>, Document, Unrolled, Performance) {
    let doc = orchestra_io::from_bytes(black_box(&bytes)).unwrap();
    let path = Unrolled::new(&doc).unwrap();
    let performance = Performance::new(&doc, &path).unwrap();
    black_box((bytes, doc, path, performance))
}

// One edit end to end: the command, the path's update, the played notes' update.
#[library_benchmark]
#[bench::pitch_normal(edit_input(Size::Normal, Edit::Pitch))]
#[bench::pitch_heavy(edit_input(Size::Heavy, Edit::Pitch))]
#[bench::daw_normal(edit_input(Size::Normal, Edit::Daw))]
#[bench::daw_heavy(edit_input(Size::Heavy, Edit::Daw))]
fn edit(
    input: (Editor, Unrolled, Performance, Command),
) -> (Editor, Unrolled, Performance, ChangeSet) {
    let (mut editor, mut path, mut performance, command) = input;
    let changes = editor.execute(black_box(&command)).unwrap();
    path.update(editor.document(), &changes).unwrap();
    performance
        .update(editor.document(), &path, &changes)
        .unwrap();
    black_box((editor, path, performance, changes))
}

// The unrolled path alone.
#[library_benchmark]
#[bench::normal(document(Size::Normal))]
fn unroll(doc: Document) -> (Document, Unrolled) {
    let path = Unrolled::new(black_box(&doc)).unwrap();
    black_box((doc, path))
}

// The file's bytes.
#[library_benchmark]
#[bench::normal(document(Size::Normal))]
fn save(doc: Document) -> (Document, Vec<u8>) {
    let bytes = orchestra_io::to_bytes(black_box(&doc)).unwrap();
    black_box((doc, bytes))
}

library_benchmark_group!(name = phase, benchmarks = [open, edit, unroll, save]);

main!(library_benchmark_groups = phase);
