//! Instruction-count benchmarks of the allocation counter (Gungraun, ADR-0016 §1).
//!
//! # Why benchmark a test helper?
//! Two reasons. First, this is the **pipeline benchmark** of step F1.02: it proves end to end
//! that `cargo xtask bench`, Valgrind, `gungraun-runner` and the CI job work, before the first
//! real hot path (the rational type, F1.03) exists. Second, the counter's own overhead matters:
//! every allocation in a test binary that installs it pays one thread-local update, and the
//! numbers below make that cost visible (it should be a handful of instructions on top of the
//! system allocator).
//!
//! # Reading the numbers
//! Gungraun runs each benchmark once under Callgrind and reports instructions executed (`Ir`),
//! estimated cache behaviour and estimated cycles. Instruction counts are deterministic for a
//! given binary, which is why ADR-0007 prefers them to wall-clock times on shared CI runners.
//!
//! # Comments and lints in this file
//! Gungraun's `#[library_benchmark]` macro rejects every attribute except its own
//! `#[bench]`/`#[benches]`, doc comments included (a doc comment is a `#[doc]` attribute), so the
//! benchmark functions are described with plain `//` comments. The modules, constants and
//! functions that the macros generate around them carry no docs and use fully qualified paths;
//! the crate-level `allow` below covers exactly those three lints, for this benchmark binary only.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_test_support::{AllocationStats, count_allocations, thread_stats};

orchestra_test_support::install_counting_allocator!();

// Cost of one counter snapshot: the primitive every measurement is built from. It must stay a
// few instructions (one thread-local load).
#[library_benchmark]
fn snapshot() -> AllocationStats {
    black_box(thread_stats())
}

// Cost of allocating and freeing one 64-byte buffer through the counting allocator: system
// allocator plus two counter updates.
#[library_benchmark]
fn allocate_and_free_64_bytes() {
    drop(black_box(Vec::<u8>::with_capacity(black_box(64))));
}

// Cost of a complete measurement of an empty closure: installation probe (one allocation and
// one free) plus two snapshots. This is the fixed overhead each "no allocation" assertion adds
// to a test.
#[library_benchmark]
fn measure_empty_closure() -> AllocationStats {
    // The `Result` is resolved with a fallback instead of `unwrap()`, so the benchmark has no
    // panic path that would distort the instruction count.
    let stats = count_allocations(|| ()).map_or(AllocationStats::ZERO, |((), s)| s);
    black_box(stats)
}

library_benchmark_group!(
    name = counting,
    benchmarks = [snapshot, allocate_and_free_64_bytes, measure_empty_closure]
);

main!(library_benchmark_groups = counting);
