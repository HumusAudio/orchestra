//! Instruction-count benchmark of the unrolling of the form (SCALETTA F1.12, P7).
//!
//! # Why this operation
//! The path is rebuilt whole whenever the form, the bars or the maps change (ADR-0025 P7): its cost
//! is paid on every such edit, so it is measured on a score far fuller of repeats than a real one.
//!
//! # The score
//! The one of `orchestra-core-model`'s `benches/form.rs`: 400 bars of 4/4 in 50 sections of 8
//! bars, each with a start repeat on its first bar and three one-bar voltas on its last three
//! ("1. :‖ 2. :‖ 3."), so every section plays its first five bars three times and each volta once:
//! 50 × 18 = 900 bars played. A second variant adds, in every section, a segno on its first bar and
//! a D.S. on pass 2 at the end of its fifth bar that plays the repeats again (50 markers and 50
//! jumps): each section is then played 29 bars long, 50 × 29 = 1 450 bars. The setup checks both
//! lengths, so this comment cannot drift from the code.
//!
//! # Setup
//! The document is built by the argument expression, outside the measured region, and returned
//! so that dropping it is not measured either; the path built is returned too.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid constants; never part of the measured code"
)]
#![allow(
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{
    BarId, Document, DocumentBuilder, JumpFires, JumpSpec, Key, MarkerKind, Metronome, Mode,
    PassSet, RepeatsAfterJump, TempoMark,
};
use orchestra_core_time::{Duration, Meter, MeterChange, MeterMap, Rational, Tempo};
use orchestra_playback::Unrolled;

// Bars of the document.
const BARS: usize = 400;

// The builder of the score described in the module comment, with its bars.
fn builder() -> (DocumentBuilder, Vec<BarId>) {
    let meters = MeterMap::new(MeterChange::new(Meter::new(&[4], 4).unwrap())).unwrap();
    let tempo = Tempo::new(
        Duration::from_rational(Rational::new(1, 4).unwrap()),
        Rational::from_integer(100).unwrap(),
    )
    .unwrap();
    let mut b = DocumentBuilder::new(
        meters,
        TempoMark::immediate(None, Metronome::shown(tempo)).unwrap(),
        Key::traditional(0, Mode::Major).unwrap(),
    )
    .unwrap();
    let bars: Vec<BarId> = (0..BARS).map(|_| b.add_bar().unwrap()).collect();
    for section in (0..BARS).step_by(8) {
        b.add_repeat_start(bars[section]).unwrap();
        for (k, at) in (section + 5..section + 8).enumerate() {
            let pass = u8::try_from(k + 1).unwrap();
            b.add_volta(
                bars[at],
                bars[at],
                PassSet::range(pass, pass).unwrap(),
                k < 2,
                None,
            )
            .unwrap();
            if k < 2 {
                b.add_repeat_end(bars[at], 3).unwrap();
            }
        }
    }
    (b, bars)
}

// The score with repeats and voltas only (900 bars played, checked).
fn repeats() -> Document {
    let document = builder().0.build().unwrap();
    assert_eq!(Unrolled::new(&document).unwrap().played().len(), 900);
    document
}

// The score with, in every section, a segno and a D.S. on pass 2 that plays the repeats again
// (1 450 bars played, checked).
fn jumps() -> Document {
    let (mut b, bars) = builder();
    for section in (0..BARS).step_by(8) {
        let segno = b
            .add_marker(bars[section], MarkerKind::Segno, None)
            .unwrap();
        let spec = JumpSpec {
            fires: JumpFires::OnPass(2),
            repeats: RepeatsAfterJump::Play,
            ..JumpSpec::dal_segno(segno)
        };
        b.add_jump(bars[section + 4], spec, None).unwrap();
    }
    let document = b.build().unwrap();
    assert_eq!(Unrolled::new(&document).unwrap().played().len(), 1450);
    document
}

#[library_benchmark]
#[bench::repeats(repeats())]
#[bench::jumps(jumps())]
fn unroll(document: Document) -> (Document, Option<Unrolled>) {
    let unrolled = black_box(Unrolled::new(black_box(&document))).ok();
    (document, unrolled)
}

library_benchmark_group!(name = unrolling, benchmarks = [unroll]);

main!(library_benchmark_groups = unrolling);
