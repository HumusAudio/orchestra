//! Instruction-count benchmarks of the played notes and of their incremental update (ADR-0027 §9
//! and §11, H13; SCALETTA F1.13c part 2).
//!
//! # Why these operations
//! - `full`: the whole performance of the heavy score, computed once when a project is opened and
//!   again after every change of the form or of the bars.
//! - `update_note`: the update after one note of the first piano is changed (its articulations),
//!   which recomputes the window of its cell: the path of a keystroke. Budget ≤ 1 ms (ADR-0027 §9).
//! - `update_dynamic`: the update after one dynamic is added to the first piano, which rebuilds the
//!   piano's timelines and reads the velocities of its notes again (H11).
//!
//! # The score
//! The heavy plain score of `orchestra-test-scores` (ADR-0031; 1 000 bars, 30 staves, 41
//! voices), with a level
//! every 8 bars and a crescendo every 16 bars for every instrument, added with the editor in the
//! setup.
//!
//! # Setup
//! The document, the path, the performance and the change set are built by the argument
//! expression, outside the measured region, and returned so that dropping them is not measured
//! either. Each update runs once: it costs far more than the few thousand instructions below which
//! ADR-0017 §4 asks for batches.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    clippy::indexing_slicing,
    reason = "setup code with known-valid constants; never part of the measured code"
)]
#![allow(
    clippy::large_types_passed_by_value,
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::{
    Articulation, ArticulationSet, ChangeSet, Command, Document, DynamicLevel, DynamicMark,
    DynamicPlacement, Editor, EventChange, HairpinShape, MarkSpec, ScorePoint,
};
use orchestra_core_time::{BarIndex, Duration};
use orchestra_playback::{Performance, Unrolled};

// The plain preset of the reference scores (ADR-0031): `plain(size, editing)`.
use orchestra_test_scores::{Size, plain};

// The heavy score with dynamics and hairpins, in an editor.
fn editor() -> Editor {
    let mut editor = Editor::new(plain(Size::Heavy, false));
    let doc = editor.document();
    let bars: Vec<_> = doc.bars().ids().to_vec();
    let mut commands = Vec::new();
    for track in doc.tracks() {
        let instrument = track.instrument();
        let staff = instrument.staves()[0].id();
        let placement = DynamicPlacement::instrument(staff);
        for (i, &bar) in bars.iter().enumerate().step_by(8) {
            let level = [DynamicLevel::P, DynamicLevel::Mf, DynamicLevel::F][(i / 8) % 3];
            commands.push(Command::AddMark(MarkSpec::Dynamic {
                instrument: instrument.id(),
                at: ScorePoint::new(bar, Duration::ZERO),
                placement,
                mark: DynamicMark::Level(level),
            }));
            if i % 16 == 0 && i + 2 < bars.len() {
                commands.push(Command::AddMark(MarkSpec::Hairpin {
                    instrument: instrument.id(),
                    start: ScorePoint::new(bar, Duration::ZERO),
                    end: ScorePoint::new(bars[i + 2], Duration::ZERO),
                    placement,
                    shape: HairpinShape::CRESCENDO,
                }));
            }
        }
    }
    for command in commands {
        editor.execute(&command).unwrap();
    }
    editor
}

// The document and its path.
fn setup_full() -> (Document, Unrolled) {
    let doc = editor().document().clone();
    let path = Unrolled::new(&doc).unwrap();
    (doc, path)
}

// The document after `command`, its updated path, the performance before and the change set.
fn after(command: fn(&Document) -> Command) -> (Document, Unrolled, Performance, ChangeSet) {
    let mut editor = editor();
    let mut path = Unrolled::new(editor.document()).unwrap();
    let performance = Performance::new(editor.document(), &path).unwrap();
    let command = command(editor.document());
    let changes = editor.execute(&command).unwrap();
    let doc = editor.document().clone();
    path.update(&doc, &changes).unwrap();
    (doc, path, performance, changes)
}

// An accent on the first chord of the first piano's first voice in bar 500.
fn accent(doc: &Document) -> Command {
    let voice = doc.tracks()[0].instrument().voices()[0].id();
    let bar = doc.bars().id_at(BarIndex::new(500)).unwrap();
    let event = doc
        .events(voice, bar)
        .unwrap()
        .iter()
        .find(|e| e.event().chord().is_some())
        .unwrap()
        .event()
        .id();
    Command::ChangeEvent {
        event,
        change: EventChange::Articulations(ArticulationSet::EMPTY.with(Articulation::Accent)),
    }
}

// A pp for the first piano at bar 500, beat 2.
fn dynamic(doc: &Document) -> Command {
    let instrument = doc.tracks()[0].instrument();
    Command::AddMark(MarkSpec::Dynamic {
        instrument: instrument.id(),
        at: ScorePoint::new(
            doc.bars().id_at(BarIndex::new(500)).unwrap(),
            Duration::from_rational(orchestra_core_time::Rational::new(1, 4).unwrap()),
        ),
        placement: DynamicPlacement::instrument(instrument.staves()[0].id()),
        mark: DynamicMark::Level(DynamicLevel::Pp),
    })
}

fn setup_note() -> (Document, Unrolled, Performance, ChangeSet) {
    after(accent)
}

fn setup_dynamic() -> (Document, Unrolled, Performance, ChangeSet) {
    after(dynamic)
}

// The whole performance of the heavy score.
#[library_benchmark]
#[bench::heavy(setup_full())]
fn full(input: (Document, Unrolled)) -> (Document, Unrolled, Performance) {
    let (doc, path) = input;
    let performance = black_box(Performance::new(&doc, &path).unwrap());
    (doc, path, performance)
}

// The update after one note changed.
#[library_benchmark]
#[bench::heavy(setup_note())]
fn update_note(
    input: (Document, Unrolled, Performance, ChangeSet),
) -> (Document, Unrolled, Performance, ChangeSet) {
    let (doc, path, mut performance, changes) = input;
    black_box(performance.update(&doc, &path, &changes).unwrap());
    (doc, path, performance, changes)
}

// The update after one dynamic added.
#[library_benchmark]
#[bench::heavy(setup_dynamic())]
fn update_dynamic(
    input: (Document, Unrolled, Performance, ChangeSet),
) -> (Document, Unrolled, Performance, ChangeSet) {
    let (doc, path, mut performance, changes) = input;
    black_box(performance.update(&doc, &path, &changes).unwrap());
    (doc, path, performance, changes)
}

library_benchmark_group!(
    name = perform,
    benchmarks = [full, update_note, update_dynamic]
);

main!(library_benchmark_groups = perform);
