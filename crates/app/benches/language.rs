//! Instruction-count benchmark of changing the interface's language while the program runs
//! (SCALETTA F2.13, ADR-0053 LR1).
//!
//! # The case
//! `language_change`: the demonstration in en-US in the program's window (960 × 600 logical
//! pixels, scale 1), drawn once, with the Preferences open on their Language section, as the
//! user has them when choosing. Then the whole change to Italian, as one choice in the drop-down
//! does it: the Italian catalogue parsed (with en-US's for its fallback), every text of the
//! interface formatted, the Preferences closed, the registry renamed, the menu bar renamed, the
//! content removed and built again, the Preferences opened again on Language, everything laid
//! out, recorded and **drawn** (the whole window is damaged), and the accessibility tree's update
//! taken. That is the path from the user's input to the next frame.
//!
//! # Budget
//! The 50 ms from input to frame of CLAUDE.md §5 on the reference laptop. At the ~1.5–2
//! instructions per nanosecond measured for this code there, 50 ms is about 75 M instructions;
//! the case must stay well below. It runs once per change of language, never on a frame's path.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid inputs; never part of the measured code"
)]
#![allow(
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_app::{Demo, SceneContext};
use orchestra_i18n::Locale;
use orchestra_ui::{
    ButtonState, CpuRenderer, DisplayList, Image, InputEvent, Key, Modifiers, NamedKey,
    PhysicalKey, Rect, Renderer, WindowApp,
};

/// The window's size, the program's (`main.rs`), logical pixels at scale 1.
const WIDTH: u32 = 960;
/// See [`WIDTH`].
const HEIGHT: u32 = 600;

/// The demonstration with what draws it.
struct Window {
    /// The demonstration.
    demo: Demo,
    /// Its display list.
    list: DisplayList,
    /// The renderer.
    renderer: CpuRenderer,
    /// The window's pixels.
    image: Image,
}

/// Draws what changed (the damage) into the window's pixels.
fn draw(window: &mut Window) {
    let damage = window.list.take_damage();
    window
        .renderer
        .render(
            &window.list,
            &orchestra_app::theme(),
            &damage,
            1.0,
            &mut window.image,
        )
        .unwrap();
}

/// The demonstration in en-US, drawn, with the Preferences open on Language and drawn, the
/// accessibility tree taken: what the user sees before choosing.
fn language_section() -> Window {
    let context = SceneContext::new().unwrap();
    let mut demo = Demo::new(
        &context.faces,
        &orchestra_app::theme(),
        &context.app_name,
        &context.demo,
    );
    let mut list = DisplayList::new();
    #[allow(
        clippy::cast_precision_loss,
        reason = "the window's size is a few hundred pixels: exact as f32"
    )]
    demo.layout(
        Rect::from_origin_size(0.0, 0.0, WIDTH as f32, HEIGHT as f32),
        &mut list,
    );
    let ids = demo.actions().unwrap();
    demo.run_action(ids.preferences, &mut list);
    // The list of sections has the focus: Down shows Language.
    for state in [ButtonState::Pressed, ButtonState::Released] {
        demo.input(
            &InputEvent::Key {
                key: Key::Named(NamedKey::ArrowDown),
                physical: PhysicalKey::Other,
                state,
                repeat: false,
                modifiers: Modifiers::default(),
            },
            &mut list,
        );
    }
    assert!(demo.language_choice().is_some());
    let mut window = Window {
        demo,
        list,
        renderer: CpuRenderer::new(context.faces),
        image: Image::new(WIDTH, HEIGHT).unwrap(),
    };
    draw(&mut window);
    let _ = window.demo.access_update(false);
    window
}

// The whole change from en-US to Italian, drawn, with the accessibility update (see the module
// documentation).
#[library_benchmark]
#[bench::window(language_section())]
fn language_change(mut window: Window) -> Window {
    let changed = window
        .demo
        .set_language(black_box(Locale::It), &mut window.list)
        .unwrap();
    assert!(changed);
    draw(&mut window);
    black_box(window.demo.access_update(false));
    window
}

library_benchmark_group!(name = language, benchmarks = [language_change]);

main!(library_benchmark_groups = language);
