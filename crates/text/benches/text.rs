//! Instruction-count benchmarks of the text crate (ADR-0044 TX12; SCALETTA F2.07b).
//!
//! # The cases
//! - `shape_line`: one interface line of 40 characters (a menu entry, a label), shaped and laid
//!   out without a width, with a warm shaper (its plans compiled, its vectors grown): what a
//!   widget pays when its text changes.
//! - `wrap_paragraph`: a dialog paragraph of about 400 characters wrapped at 300 logical
//!   pixels, warm too: shaping plus UAX #14 plus the greedy filling of the lines.
//! - `outline_glyphs`: the outlines of the 26 lowercase letters of Inter at 13 px and of a
//!   Bravura G clef at 32 px, into a sink that only counts: what filling the glyph cache costs
//!   per glyph before rasterising (step F2.07b part 2).
//!
//! # Budgets (CLAUDE.md §5, with the rule of F1.16c: 1 instruction per nanosecond)
//! Text changes must fit in the 50 ms from input to frame together with everything else, and a
//! re-layout of the score must take ≤ 16 ms: a line should cost well under 0.1 ms (100 000
//! instructions) and a paragraph under 1 ms. The real times are measured in F2.23.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid inputs; never part of the measured code"
)]
#![allow(
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_text::{FaceId, Faces, GlyphId, OutlineSink, Shaper, TextLayout, TextStyle};

// A 40-character interface line.
const LINE: &str = "Insert bars before the selection (Ctrl+B)";

// A dialog paragraph of about 400 characters, with the punctuation of real messages.
const PARAGRAPH: &str = "The project was saved by a newer version of Orchestra and \
    cannot be opened here. Its file format is version 3, while this version reads files up to \
    version 2. Your work is safe: nothing was changed in the file. Update Orchestra to the \
    latest version to open it, or ask whoever sent you the project to export it again in an \
    older format, if their version allows it. The file is stored at its usual place.";

// Everything a measured call needs, prepared outside the measured region.
struct Prepared {
    faces: Faces,
    shaper: Shaper,
    layout: TextLayout,
}

// The faces, a shaper and a layout, warmed by one layout of `text` at `width`.
fn warm(text: &str, width: Option<f32>) -> Prepared {
    let faces = Faces::bundled().unwrap();
    let mut shaper = Shaper::new();
    let mut layout = TextLayout::new();
    shaper
        .layout(&faces, text, body(), width, &mut layout)
        .unwrap();
    Prepared {
        faces,
        shaper,
        layout,
    }
}

// Inter Regular at 13 px, the body text.
const fn body() -> TextStyle {
    TextStyle::new(FaceId::InterRegular, 13.0)
}

#[library_benchmark]
#[bench::line(warm(LINE, None))]
fn shape_line(mut input: Prepared) -> Prepared {
    input
        .shaper
        .layout(
            &input.faces,
            black_box(LINE),
            body(),
            None,
            &mut input.layout,
        )
        .unwrap();
    input
}

#[library_benchmark]
#[bench::paragraph(warm(PARAGRAPH, Some(300.0)))]
fn wrap_paragraph(mut input: Prepared) -> Prepared {
    input
        .shaper
        .layout(
            &input.faces,
            black_box(PARAGRAPH),
            body(),
            Some(300.0),
            &mut input.layout,
        )
        .unwrap();
    input
}

// A sink that only counts the segments, so the benchmark measures skrifa, not a path builder.
#[derive(Default)]
struct Count(usize);

impl OutlineSink for Count {
    fn move_to(&mut self, _: f32, _: f32) {
        self.0 += 1;
    }
    fn line_to(&mut self, _: f32, _: f32) {
        self.0 += 1;
    }
    fn quad_to(&mut self, _: f32, _: f32, _: f32, _: f32) {
        self.0 += 1;
    }
    fn cubic_to(&mut self, _: f32, _: f32, _: f32, _: f32, _: f32, _: f32) {
        self.0 += 1;
    }
    fn close(&mut self) {
        self.0 += 1;
    }
}

// The 26 lowercase letters of Inter and the Bravura G clef, with the faces warmed.
fn glyphs() -> (Faces, Vec<GlyphId>, GlyphId) {
    let faces = Faces::bundled().unwrap();
    let letters: Vec<GlyphId> = ('a'..='z')
        .map(|c| faces.glyph_for_char(FaceId::InterRegular, c).unwrap())
        .collect();
    let clef = faces.glyph_for_char(FaceId::Bravura, '\u{E050}').unwrap();
    let mut count = Count::default();
    faces
        .draw_outline(FaceId::Bravura, clef, 32.0, &mut count)
        .unwrap();
    faces
        .draw_outline(FaceId::InterRegular, letters[0], 13.0, &mut count)
        .unwrap();
    (faces, letters, clef)
}

#[library_benchmark]
#[bench::letters_and_clef(glyphs())]
fn outline_glyphs(input: (Faces, Vec<GlyphId>, GlyphId)) -> usize {
    let (faces, letters, clef) = input;
    let mut count = Count::default();
    for &letter in &letters {
        faces
            .draw_outline(FaceId::InterRegular, black_box(letter), 13.0, &mut count)
            .unwrap();
    }
    faces
        .draw_outline(FaceId::Bravura, black_box(clef), 32.0, &mut count)
        .unwrap();
    count.0
}

library_benchmark_group!(
    name = text,
    benchmarks = [shape_line, wrap_paragraph, outline_glyphs]
);

main!(library_benchmark_groups = text);
