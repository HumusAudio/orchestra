//! Instruction-count benchmarks of the settings file (ADR-0050 DG6, SCALETTA F2.12a2): encoding
//! and reading a **large but plausible** settings file, in batches (ADR-0017 §4).
//!
//! # What is measured
//! - `settings_write`: 100 × `settings::to_bytes` of the settings below;
//! - `settings_read`: 100 × `settings::from_bytes` of their bytes (the lenient reader through a
//!   `serde_json::Value` tree).
//!
//! The settings: 10 custom themes of 20 overrides per half (every kind), 60 changed actions of two
//! shortcuts each, 20 playback values. Ordinary files are far smaller (a few overrides, a handful
//! of shortcuts): this is the upper end a user who customises a lot might reach. The read happens
//! once at start-up and the write half a second after a change (on a thread of its own, DG6/S5),
//! so neither is on a frame's path. Measured on 2026-11-23 (F2.12a2): about 0.72 M instructions
//! per encoding and 3.1 M per reading of these settings (≈ 42 KB of JSON): by the rule of F1.16c
//! (one instruction per nanosecond on the reference laptop) about 0.7 ms and 3 ms, the reading once
//! at start-up (budget 3 s), the encoding on the writer thread; an ordinary file costs a small
//! fraction of it.
//!
//! The file system is not touched: the safe write's system calls are the same as the project
//! file's, and their time is the disk's, not ours.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid inputs; never part of the measured code"
)]
#![allow(
    clippy::large_types_passed_by_value,
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::collections::BTreeMap;
use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_io::settings::{
    self, CustomTheme, Settings, ShortcutEntry, ThemeChoice, ThemeOverride, ThemeSettings,
};

// How many encodings or readings one benchmark run makes (ADR-0017 §4: batches, so that a
// drift of a few instructions in unrelated code does not move the result).
const BATCH: usize = 100;

// One half's overrides: the five kinds in turn, 20 in all.
fn overrides(seed: u32) -> Vec<ThemeOverride> {
    (0..20u32)
        .map(|i| match i % 5 {
            0 => ThemeOverride::Color {
                token: "surface-raised".to_owned(),
                rgba: seed.wrapping_mul(2_654_435_761).wrapping_add(i),
            },
            1 => ThemeOverride::Shape {
                token: "corner-radius".to_owned(),
                value: 4,
            },
            2 => ThemeOverride::Family {
                token: "family-ui".to_owned(),
                family: "inter".to_owned(),
            },
            3 => ThemeOverride::TextSize {
                token: "size-body".to_owned(),
                size: 14,
            },
            _ => ThemeOverride::Density("compact".to_owned()),
        })
        .collect()
}

// The large settings described in the module documentation.
fn large_settings() -> Settings {
    let custom = (0..10u32)
        .map(|n| CustomTheme {
            name: format!("Theme {n}"),
            base: "slate".to_owned(),
            light: overrides(n),
            dark: overrides(n.wrapping_add(100)),
        })
        .collect();
    let shortcuts = (0..60)
        .map(|n| ShortcutEntry {
            action: format!("group.action-{n}"),
            keys: vec![
                format!("Primary+Shift+F{}", n % 24 + 1),
                "Alt+F7".to_owned(),
            ],
        })
        .collect();
    let playback: BTreeMap<String, i64> = (0..20).map(|n| (format!("value-{n}"), n * 3)).collect();
    Settings {
        theme: ThemeSettings {
            choice: ThemeChoice::Custom("Theme 3".to_owned()),
            custom,
            ..ThemeSettings::default()
        },
        shortcuts,
        playback,
        ..Settings::default()
    }
}

// The bytes of the large settings.
fn large_bytes() -> Vec<u8> {
    settings::to_bytes(&large_settings()).unwrap()
}

#[library_benchmark]
#[bench::large(large_settings())]
fn settings_write(settings: Settings) -> (Settings, usize) {
    let mut total = 0;
    for _ in 0..BATCH {
        total += settings::to_bytes(black_box(&settings)).unwrap().len();
    }
    (settings, black_box(total))
}

#[library_benchmark]
#[bench::large(large_bytes())]
fn settings_read(bytes: Vec<u8>) -> (Vec<u8>, usize) {
    let mut total = 0;
    for _ in 0..BATCH {
        let parsed = settings::from_bytes(black_box(&bytes)).unwrap();
        total += parsed.settings.shortcuts.len() + parsed.warnings.len();
    }
    (bytes, black_box(total))
}

library_benchmark_group!(
    name = settings_file,
    benchmarks = [settings_write, settings_read]
);

main!(library_benchmark_groups = settings_file);
