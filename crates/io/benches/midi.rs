//! Instruction-count benchmarks of the MIDI export (ADR-0032, "Tests and benchmarks"; SCALETTA
//! F1.18).
//!
//! - `export_bytes`: the bytes of the file from a document, its path and its performance
//!   (`midi::export`): the tempo rebuilt from the path's seconds, the time signatures, the
//!   channels, notes, bends and CC 11 curves, the encoding.
//!
//! The budgets proposed by ADR-0032, with the rule of F1.16c (1 instruction per nanosecond on the
//! reference laptop, deliberately pessimistic): the normal full score within 100 M instructions
//! (≈ 0.1 s), the heavy one within 2 G (≈ 2 s, like its opening). An export is a user command,
//! not a hot path of editing; the budget only keeps it from being noticeably slow.
//!
//! # The scores
//! The normal and heavy **full** scores of `orchestra-test-scores` (ADR-0031): forms with repeats
//! and jumps, gradual tempo changes, dynamics and accents (so CC 11 curves), the real orchestra
//! (the heavy one has 28 instruments, so shared channels). The path and the performance are
//! computed outside the measured region, which measures the export alone; they are returned with
//! the bytes, so that dropping them is not measured either.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid inputs; never part of the measured code"
)]
#![allow(
    clippy::large_types_passed_by_value,
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::Document;
use orchestra_io::midi::{MidiExport, MidiOptions, export};
use orchestra_playback::{Performance, Unrolled};
use orchestra_test_scores::{Size, full};

// What the export reads: the document, its path, its performance.
type Input = (Document, Unrolled, Performance);

// The full score of this size with its path and performance.
fn input(size: Size) -> Input {
    let doc = full(size);
    let path = Unrolled::new(&doc).unwrap();
    let performance = Performance::new(&doc, &path).unwrap();
    (doc, path, performance)
}

#[library_benchmark]
#[bench::normal(input(Size::Normal))]
#[bench::heavy(input(Size::Heavy))]
fn export_bytes(input: Input) -> (Input, MidiExport) {
    let (doc, path, performance) = &input;
    let out = export(
        black_box(doc),
        black_box(path),
        black_box(performance),
        &MidiOptions::new(),
    )
    .unwrap();
    (input, black_box(out))
}

library_benchmark_group!(name = midi, benchmarks = [export_bytes]);

main!(library_benchmark_groups = midi);
