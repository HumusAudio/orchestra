//! Instruction-count benchmarks of the project file (ADR-0029 S12; SCALETTA F1.15b part 2).
//!
//! - `save_bytes`: a document's file bytes (`to_bytes`): its description, the conversion to the
//!   schema, the JSON with one record per line.
//! - `load_bytes`: a document from its file bytes (`from_bytes`): the version, the strict JSON
//!   reading, the conversion, and `Document::from_parts` (the replay through the builder and
//!   `validate`).
//!
//! The budget of ADR-0007 is the opening of 100 bars in ≤ 1 s on the reference laptop: the normal
//! score must stay far below it. The heavy score (1 000 bars × 30 staves) shows the growth.
//! Without the disk: what the disk adds depends on the machine, not on our code.
//!
//! # The scores
//! The normal and heavy scores of `core-model`'s tests (`tests/common/score.rs`). Each benchmark
//! runs once on the whole score (millions of instructions need no batch, ADR-0017 §4); the input
//! is prepared outside the measured region and returned, so that dropping it is not measured.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid inputs; never part of the measured code"
)]
#![allow(
    clippy::large_types_passed_by_value,
    clippy::needless_pass_by_value,
    reason = "Gungraun passes the prepared input by value, outside the measured region"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_model::Document;

#[path = "../../core-model/tests/common/score.rs"]
mod score;

use score::Size;

// The document of this size.
fn document(size: Size) -> Document {
    score::score(size, false)
}

// The file bytes of the document of this size.
fn bytes(size: Size) -> Vec<u8> {
    orchestra_io::to_bytes(&score::score(size, false)).unwrap()
}

#[library_benchmark]
#[bench::normal(document(Size::Normal))]
#[bench::heavy(document(Size::Heavy))]
fn save_bytes(doc: Document) -> (Document, Vec<u8>) {
    let bytes = orchestra_io::to_bytes(black_box(&doc)).unwrap();
    (doc, black_box(bytes))
}

#[library_benchmark]
#[bench::normal(bytes(Size::Normal))]
#[bench::heavy(bytes(Size::Heavy))]
fn load_bytes(bytes: Vec<u8>) -> (Vec<u8>, Document) {
    let doc = orchestra_io::from_bytes(black_box(&bytes)).unwrap();
    (bytes, black_box(doc))
}

library_benchmark_group!(name = project, benchmarks = [save_bytes, load_bytes]);

main!(library_benchmark_groups = project);
