//! Instruction-count benchmarks of [`Rational`] (Gungraun, ADR-0016 §1; SCALETTA F1.03b).
//!
//! # What is measured
//! The operations ADR-0015 §9 names: sum (equal and different denominators, and a case whose
//! intermediate values exceed 64 bits, so that the 128-bit gcd runs), difference, product,
//! quotient, comparison (equal and different denominators), reduction in `new`, and an error path
//! (results that overflow). Every hot path of `core-time` that later steps add gets its own file
//! next to this one.
//!
//! # Why batches of 64 operations?
//! A single rational operation is a few dozen instructions, comparable with the fixed cost of the
//! benchmark itself (call, `black_box`, loop). The regression gate of ADR-0017 fails a pull request
//! when a count grows by more than a percentage: on a count of 50, one extra instruction would
//! already be 2%. Running each operation on a batch of 64 different inputs makes the counts large
//! enough (thousands) that only real changes in the arithmetic move them, and it exercises a
//! realistic mix of values instead of one lucky case. Divide by 64 for the cost of one operation.
//!
//! # Why are the inputs `const` arrays?
//! `Rational` constructors are `const fn` (F1.03), so the inputs are computed **at compile time**
//! and the measured code contains only the operation under test. Reading them through
//! `black_box(&ARRAY)` stops the compiler from evaluating the operations at compile time too
//! (they are `const fn` as well), which would leave nothing to measure.
//!
//! # Comments and lints in this file
//! Gungraun's `#[library_benchmark]` macro rejects every attribute except its own, doc comments
//! included, so the benchmark functions have plain `//` comments; the items the macros generate
//! have no docs and use qualified paths. The crate-level `allow` covers exactly those lints, plus
//! `panic` for the compile-time construction helper (see [`q`]). Same approach as
//! `crates/test-support/benches/counting.rs`.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
// The input tables are built in `const` blocks, where `i64::try_from` is not callable. Every cast
// there converts a loop index below `BATCH` (64) or a value already reduced modulo 2³⁰, so none
// of them can wrap or lose a sign; the casts only exist in compile-time code.
#![allow(
    clippy::cast_possible_wrap,
    clippy::cast_sign_loss,
    reason = "compile-time table construction with values far inside the i64 range (see above)"
)]

use std::cmp::Ordering;
use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_time::{Rational, RationalError};

// Number of operations per benchmark (see the module documentation).
const BATCH: usize = 64;

// Builds `n/d` at compile time. Only ever called in `const` items: a panic there is a **compile
// error** (the build stops), never a run-time panic, so the benchmark has no panic path.
#[allow(
    clippy::panic,
    reason = "evaluated only in const items: a failure is a compile error, not a run-time panic"
)]
const fn q(n: i64, d: i64) -> Rational {
    match Rational::new(n, d) {
        Ok(r) => r,
        Err(_) => panic!("benchmark input is not a valid rational"),
    }
}

// Musical denominators: plain note values (powers of two) and tuplet values (3, 5, 6, 7, 12, …).
const DENS_A: [i64; 8] = [4, 8, 16, 3, 12, 5, 7, 32];
// A second set, chosen so that `DENS_A[k]` and `DENS_B[k]` are different and often share a
// factor (8 and 6, 12 and 24, …): the general addition path, with a non-trivial gcd.
const DENS_B: [i64; 8] = [3, 6, 5, 8, 24, 10, 9, 48];

// Pairs with equal denominators: the fast path of addition and comparison (notes inside the same
// tuplet, positions inside the same bar grid).
const SAME_DEN: [(Rational, Rational); BATCH] = {
    let mut out = [(Rational::ZERO, Rational::ZERO); BATCH];
    let mut i = 0;
    while i < BATCH {
        let d = DENS_A[i % 8];
        let k = i as i64;
        out[i] = (q(k + 1, d), q(2 * k + 1, d));
        i += 1;
    }
    out
};

// Pairs with different denominators: the general path of every operation. Numerators include
// negative values (microtiming offsets) and are never zero, so that division is always defined.
const DIFF_DEN: [(Rational, Rational); BATCH] = {
    let mut out = [(Rational::ZERO, Rational::ZERO); BATCH];
    let mut i = 0;
    while i < BATCH {
        let k = i as i64;
        let sign = if i % 3 == 0 { -1 } else { 1 };
        out[i] = (q(sign * (k + 1), DENS_A[i % 8]), q(k + 3, DENS_B[i % 8]));
        i += 1;
    }
    out
};

// Inputs of `new` that need reducing: a musical fraction scaled by a common factor (the factors
// are products of tuplet ratios, up to 16·3·5·7 = 1680, ADR-0015), with the sign on the
// denominator half of the time so that the sign normalisation runs too.
const UNREDUCED: [(i64, i64); BATCH] = {
    let factors: [i64; 8] = [2, 3, 6, 15, 105, 210, 840, 1680];
    let mut out = [(0, 1); BATCH];
    let mut i = 0;
    while i < BATCH {
        let k = i as i64;
        let f = factors[i % 8];
        let d = DENS_A[(i / 8) % 8];
        out[i] = ((k + 1) * f, if i % 2 == 0 { d * f } else { -d * f });
        i += 1;
    }
    out
};

// Modular inverse of an odd number modulo 2⁶⁴, by Newton's iteration: each step doubles the
// number of correct low bits (3 → 6 → 12 → 24 → 48 → 96), so five steps are enough.
const fn inverse_mod_2_64(p: u64) -> u64 {
    let mut inv = p;
    let mut step = 0;
    while step < 5 {
        inv = inv.wrapping_mul(2_u64.wrapping_sub(p.wrapping_mul(inv)));
        step += 1;
    }
    inv
}

// Sums whose **intermediate** values exceed 64 bits although the result is small: the case that
// makes `Rational` stricter than `num-rational` (ADR-0015 §4), and the only one that runs the
// 128-bit gcd (the 64-bit fast path of ADR-0015 §9 covers everything else).
//
// With `G = 2³⁰` and the primes `P = 1048573`, `Q = 1048571` (both just below 2²⁰), take
// `x = a/(G·P)` and `y = c/(G·Q)`. Their common denominator is `G·P·Q ≈ 2⁷⁰`, beyond 64 bits.
// Choosing `c ≡ −a·Q·P⁻¹ (mod G)` makes the numerator `a·Q + c·P` a multiple of `G`, so the
// reduced sum has a denominator of about `P·Q ≈ 2⁴⁰`, which fits. `a` is odd and `c` comes out
// odd too, so both inputs are already in lowest terms.
const WIDE: [(Rational, Rational); BATCH] = {
    const G: i64 = 1 << 30;
    const P: i64 = 1_048_573;
    const Q: i64 = 1_048_571;
    let inv_p = inverse_mod_2_64(P as u64);
    let mut out = [(Rational::ZERO, Rational::ZERO); BATCH];
    let mut i = 0;
    while i < BATCH {
        let a = 2 * (i as i64) + 1;
        // −a·Q·P⁻¹ modulo 2³⁰, computed with wrapping 64-bit arithmetic and then masked.
        let c = (0_u64.wrapping_sub((a as u64).wrapping_mul(Q as u64).wrapping_mul(inv_p))
            & (G as u64 - 1)) as i64;
        out[i] = (q(a, G * P), q(c, G * Q));
        i += 1;
    }
    out
};

// Pairs whose sum or product does not fit: the error path, which must be as cheap and as
// allocation-free as the success path.
const OVERFLOWING: [(Rational, Rational); BATCH] = {
    let mut out = [(Rational::ZERO, Rational::ZERO); BATCH];
    let mut i = 0;
    while i < BATCH {
        let k = i as i64;
        out[i] = (q(i64::MAX - k, 1), q(k + 2, 1));
        i += 1;
    }
    out
};

// Sum, equal denominators (fast path: no gcd of the denominators).
#[library_benchmark]
fn add_same_denominator() {
    for (x, y) in black_box(&SAME_DEN) {
        let _ = black_box(x.checked_add(*y));
    }
}

// Sum, different denominators (general path: gcd of the denominators, then reduction).
#[library_benchmark]
fn add_different_denominators() {
    for (x, y) in black_box(&DIFF_DEN) {
        let _ = black_box(x.checked_add(*y));
    }
}

// Sum with intermediates beyond 64 bits (128-bit gcd), result in range.
#[library_benchmark]
fn add_wide_intermediate() {
    for (x, y) in black_box(&WIDE) {
        let _ = black_box(x.checked_add(*y));
    }
}

// Difference, different denominators (negation, then the sum).
#[library_benchmark]
fn sub_different_denominators() {
    for (x, y) in black_box(&DIFF_DEN) {
        let _ = black_box(x.checked_sub(*y));
    }
}

// Product (two cross gcds, no final reduction).
#[library_benchmark]
fn mul() {
    for (x, y) in black_box(&DIFF_DEN) {
        let _ = black_box(x.checked_mul(*y));
    }
}

// Quotient (reciprocal, then the product).
#[library_benchmark]
fn div() {
    for (x, y) in black_box(&DIFF_DEN) {
        let _ = black_box(x.checked_div(*y));
    }
}

// Comparison, equal denominators (fast path: numerators only).
#[library_benchmark]
fn cmp_same_denominator() {
    for (x, y) in black_box(&SAME_DEN) {
        let _: Ordering = black_box(x.cmp(y));
    }
}

// Comparison, different denominators (two `i128` cross products).
#[library_benchmark]
fn cmp_different_denominators() {
    for (x, y) in black_box(&DIFF_DEN) {
        let _: Ordering = black_box(x.cmp(y));
    }
}

// Construction with reduction and sign normalisation.
#[library_benchmark]
fn new_with_reduction() {
    for (n, d) in black_box(&UNREDUCED) {
        let _ = black_box(Rational::new(*n, *d));
    }
}

// Error path: sums and products that overflow.
#[library_benchmark]
fn overflow_errors() {
    for (x, y) in black_box(&OVERFLOWING) {
        let _: Result<Rational, RationalError> = black_box(x.checked_add(*y));
        let _: Result<Rational, RationalError> = black_box(x.checked_mul(*y));
    }
}

library_benchmark_group!(
    name = rational,
    benchmarks = [
        add_same_denominator,
        add_different_denominators,
        add_wide_intermediate,
        sub_different_denominators,
        mul,
        div,
        cmp_same_denominator,
        cmp_different_denominators,
        new_with_reduction,
        overflow_errors
    ]
);

main!(library_benchmark_groups = rational);
