//! Instruction-count benchmarks of [`TempoMap`] (Gungraun, ADR-0016 §1; SCALETTA F1.05b).
//!
//! # What is measured
//! The lookups that ADR-0020 §6 promises in O(log n) and that the audio thread and `playback`
//! will call: position → time ([`TempoMap::time_at`]), time → position
//! ([`TempoMap::position_at`]), position → sample ([`TempoMap::sample_at`], separately in
//! constant segments and inside gradual changes, where the `f64` estimate is checked exactly with
//! `i128` arithmetic, ADR-0021 §5) and position → frame ([`TempoMap::frame_at`]). Plus one edit
//! on the editing path (a tempo change in the middle, which clones the source data and rebuilds
//! every segment).
//!
//! # The reference map
//! 150 tempo changes, one every 4 whole notes, two thirds of them gradual (3.5 whole notes long,
//! followed by an implicit constant segment), cycling through metronome marks with large prime
//! factors and several beat units, so that most boundaries are off the grid: about 250 segments,
//! more than a real score has, so that the binary searches have real depth.
//!
//! # Batches and setup
//! Each lookup benchmark runs a **batch of 64** lookups spread over the whole map (ADR-0017 §4).
//! The map and the inputs are built by Gungraun **setup** functions, whose cost is not measured;
//! the map is returned so that freeing it is not measured either.
//!
//! # Comments and lints in this file
//! Same approach as `benches/rational.rs`: Gungraun's macro rejects doc comments on benchmark
//! functions, so they have plain `//` comments, and the crate-level `allow` covers the generated
//! items.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
// The setup functions build the reference map from constants known to be valid: a failure there
// is a broken benchmark, which must stop loudly; it is never measured code.
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid constants; never part of the measured code"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_time::{
    Duration, FrameRate, GradualChange, Position, Rational, SampleRate, Seconds, Tempo,
    TempoChange, TempoMap,
};

// Number of lookups per benchmark (see the module documentation).
const BATCH: usize = 64;

// Tempo changes in the reference map (one every 4 whole notes).
const CHANGES: usize = 150;

// The rational `n/d`.
fn q(n: i64, d: i64) -> Rational {
    Rational::new(n, d).unwrap()
}

// The position `n/d` whole notes.
fn at(n: i64, d: i64) -> Position {
    Position::from_rational(q(n, d))
}

// The `i`-th tempo of the cycle: units and marks with different prime factors.
fn tempo(i: usize) -> Tempo {
    let units = [q(1, 4), q(3, 8), q(1, 8), q(1, 2)];
    let marks = [
        q(120, 1),
        q(97, 1),
        q(131, 1),
        q(185, 2),
        q(73, 1),
        q(167, 1),
        q(60, 1),
    ];
    Tempo::new(
        Duration::from_rational(units[i % units.len()]),
        marks[i % marks.len()],
    )
    .unwrap()
}

// Whether change `i` of the reference map is gradual (every one except each third).
fn is_gradual(i: usize) -> bool {
    !i.is_multiple_of(3)
}

// The reference map described in the module documentation.
fn reference_map() -> TempoMap {
    let mut map = TempoMap::new(tempo(0)).unwrap();
    for i in 1..CHANGES {
        let start = at(i64::try_from(i).unwrap() * 4, 1);
        let change = if is_gradual(i) {
            TempoChange::Gradual(GradualChange {
                from: None,
                to: tempo(i),
                end: start.checked_add(Duration::from_rational(q(7, 2))).unwrap(),
            })
        } else {
            TempoChange::Immediate(tempo(i))
        };
        map.set_change(start, change).unwrap();
    }
    map
}

// 64 change indices spread over the map (a stride coprime with 150 hits every region), keeping
// only those that satisfy `keep`.
fn spread(keep: fn(usize) -> bool) -> [usize; BATCH] {
    let candidates = (0..).map(|k: usize| k * 37 % CHANGES).filter(|&i| keep(i));
    let mut picked = [0; BATCH];
    for (slot, i) in picked.iter_mut().zip(candidates) {
        *slot = i;
    }
    picked
}

// The map and 64 points in constant segments: 3.8 whole notes after a change, which is in the
// immediate change's segment or in the constant segment after a gradual one.
fn constant_points() -> (TempoMap, [Position; BATCH]) {
    let points = spread(|_| true).map(|i| {
        at(i64::try_from(i).unwrap() * 4, 1)
            .checked_add(Duration::from_rational(q(19, 5)))
            .unwrap()
    });
    (reference_map(), points)
}

// The map and 64 points inside gradual changes: 7/5 whole notes after their start.
fn gradual_points() -> (TempoMap, [Position; BATCH]) {
    let points = spread(is_gradual).map(|i| {
        at(i64::try_from(i).unwrap() * 4, 1)
            .checked_add(Duration::from_rational(q(7, 5)))
            .unwrap()
    });
    (reference_map(), points)
}

// The map and 64 points of both kinds, alternating.
fn mixed_points() -> (TempoMap, [Position; BATCH]) {
    let (map, constant) = constant_points();
    let (_, gradual) = gradual_points();
    let points = std::array::from_fn(|k| if k % 2 == 0 { constant[k] } else { gradual[k] });
    (map, points)
}

// The map and the 48 kHz sample instants nearest to the mixed points (exact times).
fn sample_times() -> (TempoMap, [Seconds; BATCH]) {
    let (map, points) = mixed_points();
    let rate = SampleRate::new(48_000).unwrap();
    let times = points.map(|p| {
        let n = map.sample_at(p, rate).unwrap().value();
        rate.time_of_sample(n).unwrap()
    });
    (map, times)
}

// Position → time, mixed points: exact in constant segments, `f64` inside gradual ones.
#[library_benchmark]
#[bench::reference(mixed_points())]
fn time_at(input: (TempoMap, [Position; BATCH])) -> TempoMap {
    let (map, points) = input;
    for p in black_box(&points) {
        let _ = black_box(map.time_at(*p));
    }
    map
}

// Time → position at sample instants: exact in constant segments, the `i128` polynomial rounded
// to the grid inside gradual ones.
#[library_benchmark]
#[bench::reference(sample_times())]
fn position_at(input: (TempoMap, [Seconds; BATCH])) -> TempoMap {
    let (map, times) = input;
    for t in black_box(&times) {
        let _ = black_box(map.position_at(*t));
    }
    map
}

// Position → sample at 48 kHz in constant segments: the exact time, then one rounding.
#[library_benchmark]
#[bench::reference(constant_points())]
fn sample_at_constant(input: (TempoMap, [Position; BATCH])) -> TempoMap {
    let (map, points) = input;
    let rate = SampleRate::new(48_000).unwrap();
    for p in black_box(&points) {
        let _ = black_box(map.sample_at(*p, rate));
    }
    map
}

// Position → sample at 48 kHz inside gradual changes: the `f64` estimate and its exact check.
#[library_benchmark]
#[bench::reference(gradual_points())]
fn sample_at_gradual(input: (TempoMap, [Position; BATCH])) -> TempoMap {
    let (map, points) = input;
    let rate = SampleRate::new(48_000).unwrap();
    for p in black_box(&points) {
        let _ = black_box(map.sample_at(*p, rate));
    }
    map
}

// Position → frame at 30000/1001 fps, mixed points.
#[library_benchmark]
#[bench::reference(mixed_points())]
fn frame_at(input: (TempoMap, [Position; BATCH])) -> TempoMap {
    let (map, points) = input;
    let fps = FrameRate::new(q(30_000, 1001)).unwrap();
    for p in black_box(&points) {
        let _ = black_box(map.frame_at(*p, fps));
    }
    map
}

// One edit on the editing path: a gradual change in the middle of the map (clone + rebuild of
// every segment + validation). Not a batch: one edit is already tens of thousands of instructions.
#[library_benchmark]
#[bench::reference(reference_map())]
fn edit_tempo_change(mut map: TempoMap) -> TempoMap {
    let change = TempoChange::Gradual(GradualChange {
        from: None,
        to: tempo(5),
        end: at(302, 1),
    });
    let _ = black_box(map.set_change(black_box(at(301, 1)), change));
    map
}

library_benchmark_group!(
    name = tempo_map,
    benchmarks = [
        time_at,
        position_at,
        sample_at_constant,
        sample_at_gradual,
        frame_at,
        edit_tempo_change
    ]
);

main!(library_benchmark_groups = tempo_map);
