//! Instruction-count benchmarks of [`MeterMap`] (Gungraun, ADR-0016 §1; SCALETTA F1.04b).
//!
//! # What is measured
//! The lookups that ADR-0018 §4 promises in O(log n) and that the audio thread will call for the
//! metronome (F3): position → bar ([`MeterMap::locate`]), bar → position
//! ([`MeterMap::bar_start`]), point → beat ([`MeterMap::beat_of`]) and back
//! ([`MeterMap::beat_position`]), and the displayed bar number. Plus one edit on the editing path
//! (a meter change, which clones and rebuilds the map), whose budget is the 16 ms re-layout of
//! CLAUDE.md §5 rather than the audio thread's.
//!
//! # The reference map
//! 256 bars with a pickup, a meter change every 4 bars cycling through simple, compound,
//! additive and non-binary meters, a free cadenza and a per-bar grouping every 32 bars: about
//! 150 segments, more than any real score, so that the binary searches have real depth.
//!
//! # Batches and setup
//! Each lookup benchmark runs a **batch of 64** lookups spread over the whole map (ADR-0017 §4),
//! so counts are in the thousands. The map and the inputs are built by Gungraun **setup**
//! functions (`#[bench::…(…)]` arguments), whose cost is not attributed to the benchmark; the map
//! is returned by the benchmark so that freeing it is not measured either.
//!
//! # Comments and lints in this file
//! Same approach as `benches/rational.rs`: Gungraun's macro rejects doc comments on benchmark
//! functions, so they have plain `//` comments, and the crate-level `allow` covers the generated
//! items.

#![allow(
    missing_docs,
    clippy::missing_docs_in_private_items,
    unused_qualifications,
    reason = "items generated by Gungraun's macros have no docs and use qualified paths; our own \
              items are documented with plain comments because the macro rejects #[doc]"
)]
// The setup functions build the reference map from constants known to be valid: a failure there
// is a broken benchmark, which must stop loudly; it is never measured code.
#![allow(
    clippy::unwrap_used,
    reason = "setup code with known-valid constants; never part of the measured code"
)]

use std::hint::black_box;

use gungraun::prelude::*;
use orchestra_core_time::{
    BarIndex, BarKind, BarPosition, BeatGrouping, BeatPosition, Duration, IrregularBar, Meter,
    MeterChange, MeterMap, Position, Rational,
};

// Number of lookups per benchmark (see the module documentation).
const BATCH: usize = 64;

// Bars covered by the reference map.
const BARS: u32 = 256;

// A duration of `n/d` whole notes.
fn d(n: i64, den: i64) -> Duration {
    Duration::from_rational(Rational::new(n, den).unwrap())
}

// The reference map described in the module documentation.
fn reference_map() -> MeterMap {
    let meters = [
        Meter::new(&[4], 4).unwrap(),
        Meter::new(&[3], 4).unwrap(),
        Meter::new(&[6], 8).unwrap(),
        Meter::new(&[3, 2, 2], 8).unwrap(),
        Meter::new(&[4], 3).unwrap(),
        Meter::new(&[7], 8).unwrap(),
    ];
    let mut map = MeterMap::new(MeterChange::new(meters[0])).unwrap();
    map.set_irregular_bar(
        BarIndex::FIRST,
        IrregularBar {
            length: d(1, 4),
            kind: BarKind::AlignEnd,
        },
    )
    .unwrap();
    for (i, first) in (4..BARS).step_by(4).enumerate() {
        let meter = meters[i % meters.len()];
        map.set_meter_change(BarIndex::new(first), MeterChange::new(meter))
            .unwrap();
    }
    for bar in (10..BARS).step_by(32) {
        map.set_irregular_bar(
            BarIndex::new(bar),
            IrregularBar {
                length: d(5, 2),
                kind: BarKind::Free,
            },
        )
        .unwrap();
    }
    // Meter changes start at bar 4 and cycle through six meters every 24 bars, so the 7/8 sections
    // begin at bars 24, 48, 72…: count their first bar 2+2+3.
    for bar in (24..BARS).step_by(24) {
        map.set_bar_grouping(
            BarIndex::new(bar),
            BeatGrouping::new(&[2, 2, 3], 8).unwrap(),
        )
        .unwrap();
    }
    map
}

// 64 bars spread over the map (a stride coprime with 256, so every region is hit).
fn bars() -> [BarIndex; BATCH] {
    std::array::from_fn(|i| BarIndex::new(u32::try_from(i * 37 % BARS as usize).unwrap()))
}

// The map and 64 positions in the middle of the bars above.
fn positions() -> (MeterMap, [Position; BATCH]) {
    let map = reference_map();
    let points = bars().map(|bar| {
        let half = map
            .bar_length(bar)
            .unwrap()
            .checked_div(Rational::new(2, 1).unwrap());
        map.bar_start(bar)
            .unwrap()
            .checked_add(half.unwrap())
            .unwrap()
    });
    (map, points)
}

// The map and the same 64 points, as bar positions.
fn bar_positions() -> (MeterMap, [BarPosition; BATCH]) {
    let (map, points) = positions();
    let at = points.map(|p| map.locate(p).unwrap());
    (map, at)
}

// The map and 64 (bar, beat) pairs that exist (the first beat starting in each non-free bar).
fn beats() -> (MeterMap, [(BarIndex, BeatPosition); BATCH]) {
    let map = reference_map();
    let pairs = bars().map(|bar| {
        // A free bar has no beats: use the bar after it, which is regular.
        let bar = if map.is_free(bar).unwrap() {
            BarIndex::new(bar.get() + 1)
        } else {
            bar
        };
        let beat = map.beat_range(bar).unwrap().unwrap().start;
        (
            bar,
            BeatPosition {
                beat,
                offset: Duration::ZERO,
            },
        )
    });
    (map, pairs)
}

// Position → (bar, offset): binary search on the segment starts, then one division.
#[library_benchmark]
#[bench::reference(positions())]
fn locate(input: (MeterMap, [Position; BATCH])) -> MeterMap {
    let (map, points) = input;
    for p in black_box(&points) {
        let _ = black_box(map.locate(*p));
    }
    map
}

// Bar → start position: binary search on the first bars, then one multiplication.
#[library_benchmark]
#[bench::reference(reference_map())]
fn bar_start(map: MeterMap) -> MeterMap {
    for bar in black_box(&bars()) {
        let _ = black_box(map.bar_start(*bar));
    }
    map
}

// (bar, offset) → beat: segment search, then the pattern (uniform, grouped, free).
#[library_benchmark]
#[bench::reference(bar_positions())]
fn beat_of(input: (MeterMap, [BarPosition; BATCH])) -> MeterMap {
    let (map, at) = input;
    for a in black_box(&at) {
        let _ = black_box(map.beat_of(*a));
    }
    map
}

// (bar, beat) → position: the inverse of `beat_of`.
#[library_benchmark]
#[bench::reference(beats())]
fn beat_position(input: (MeterMap, [(BarIndex, BeatPosition); BATCH])) -> MeterMap {
    let (map, pairs) = input;
    for (bar, beat) in black_box(&pairs) {
        let _ = black_box(map.beat_position(*bar, *beat));
    }
    map
}

// Bar → displayed number (restart search, uncounted bars).
#[library_benchmark]
#[bench::reference(reference_map())]
fn display_number(map: MeterMap) -> MeterMap {
    for bar in black_box(&bars()) {
        let _ = black_box(map.display_number(*bar));
    }
    map
}

// One edit on the editing path: a meter change in the middle of the map (clone + rebuild +
// validation of every source entry). Not a batch: one edit is already tens of thousands of
// instructions.
#[library_benchmark]
#[bench::reference(reference_map())]
fn edit_meter_change(mut map: MeterMap) -> MeterMap {
    let meter = Meter::new(&[5], 4).unwrap();
    let _ = black_box(map.set_meter_change(black_box(BarIndex::new(130)), MeterChange::new(meter)));
    map
}

library_benchmark_group!(
    name = meter_map,
    benchmarks = [
        locate,
        bar_start,
        beat_of,
        beat_position,
        display_number,
        edit_meter_change
    ]
);

main!(library_benchmark_groups = meter_map);
