//! Spike for SCALETTA F1.06: how should the document model store the events of a voice?
//!
//! Three candidates (see `ANALYSIS.md` §7 next to this crate), all with the same event type, the
//! same 64-bit IDs (A2) and voices owned by the instrument (F2, the owner's choice):
//!
//! - [`p1`]: one sorted `Vec` per voice with **absolute** positions (B1 + D1);
//! - [`p2`]: one chunk per bar per voice, offsets **relative to the bar**, bars named by their
//!   index (B3 + D2 + C1);
//! - [`p3`]: like `p2`, but bars have **stable IDs** and the chunks sit behind `Arc`, so that a
//!   snapshot is a copy of pointers (B3 + D2 + C2 + E3).
//!
//! What is measured is only the work that **differs** between the candidates. The meter map edits
//! and the shift of the tempo changes after an edit point are the same in all three (the music
//! moves in the same way whatever the storage), so every operation receives the meter map before
//! and after the edit, prepared outside the measurement.
//!
//! This is spike code: `unwrap` is used freely, nothing is validated beyond what the measurements
//! need, and the code is thrown away once the ADR is written.

use std::collections::HashMap;
use std::hash::{BuildHasherDefault, Hasher};
use std::ops::Range;

use orchestra_core_time::{
    BarIndex, BarKind, Duration, IrregularBar, Meter, MeterChange, MeterMap, Position, Rational,
};

pub mod p1;
pub mod p2;
pub mod p3;

// ---------------------------------------------------------------------------------------------
// The event type, common to all candidates.
// ---------------------------------------------------------------------------------------------

/// A stable, never reused 64-bit identifier (alternative A2 of the analysis).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct EventId(pub u64);

/// One notehead of a chord. `pitch` stands in for the spelled pitch of F1.07 (same size class:
/// step, alteration and octave fit in a few bytes); `tied` stands in for the tie relation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Note {
    /// The notehead's own ID: ties, performance offsets and spelling are per note (ADR-0004).
    pub id: u64,
    /// Placeholder for the spelled pitch.
    pub pitch: i16,
    /// Placeholder for the tie relation.
    pub tied: bool,
}

/// A rhythmic event of a voice: a chord of 1–4 noteheads or a rest (`len == 0`).
///
/// The noteheads are stored inline (at most four in this spike) so that no candidate pays an
/// allocation per event: the real type may use a small inline vector, the comparison is the same.
/// Size: about 100 bytes, in the range of the real two-layer note (ADR-0004) without its rarer
/// optional parts.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Event {
    /// The event's ID.
    pub id: EventId,
    /// The written duration.
    pub duration: Duration,
    /// The staff the event is drawn on (F2: the voice belongs to the instrument).
    pub staff: u8,
    /// Number of used noteheads; 0 is a rest.
    pub len: u8,
    /// The noteheads; only the first `len` are meaningful.
    pub notes: [Note; 4],
}

// ---------------------------------------------------------------------------------------------
// The ID index: a hash map with a cheap hasher.
// ---------------------------------------------------------------------------------------------

/// A multiplicative (Fibonacci) hasher for sequential 64-bit IDs.
///
/// The standard SipHash is designed against hash flooding from untrusted keys; our IDs are
/// generated by the document itself, so one multiplication is enough and costs a few instructions
/// instead of about a hundred. The real model would do the same (or use `FxHash`).
#[derive(Default)]
pub struct IdHasher(u64);

impl Hasher for IdHasher {
    fn finish(&self) -> u64 {
        self.0
    }

    fn write(&mut self, bytes: &[u8]) {
        // Only `u64` keys are ever hashed; fold bytes anyway so the hasher stays correct.
        for &b in bytes {
            self.0 = (self.0 ^ u64::from(b)).wrapping_mul(0x9E37_79B9_7F4A_7C15);
        }
    }

    fn write_u64(&mut self, n: u64) {
        self.0 = n.wrapping_mul(0x9E37_79B9_7F4A_7C15);
    }
}

/// A hash map keyed by IDs.
pub type IdMap<K, V> = HashMap<K, V, BuildHasherDefault<IdHasher>>;

// ---------------------------------------------------------------------------------------------
// The interface every candidate implements.
// ---------------------------------------------------------------------------------------------

/// The operations measured on every candidate (ANALYSIS.md §7).
///
/// `before`/`after` are the meter maps before and after the edit; the edit of the map itself is
/// common to all candidates and not measured.
pub trait Model: Sized {
    /// What a background reader (layout worker, autosave, playback compile) receives.
    type Snapshot;

    /// Loads a generated score.
    fn build(spec: &Spec) -> Self;

    /// Inserts `event` in `voice` at the absolute position `at` (after the events already there).
    fn insert(&mut self, meter: &MeterMap, voice: usize, at: Position, event: Event);

    /// Deletes an event by ID and returns it.
    fn delete(&mut self, id: EventId) -> Option<Event>;

    /// The absolute position of an event, found by ID.
    fn find(&self, meter: &MeterMap, id: EventId) -> Option<Position>;

    /// Appends to `out` every event of every voice in `bars`, with absolute positions: what the
    /// layout of a page and the playback compile ask for.
    fn collect(&self, meter: &MeterMap, bars: Range<u32>, out: &mut Vec<(Position, EventId)>);

    /// A regular bar was inserted at `bar`: the music from `bar` on moves one bar later.
    fn insert_bar(&mut self, before: &MeterMap, after: &MeterMap, bar: u32);

    /// The free bar `bar` got longer: the music after it moves later.
    fn lengthen_bar(&mut self, before: &MeterMap, after: &MeterMap, bar: u32);

    /// The meter changed from `bar` on and every bar keeps its contents (behaviour (i)).
    fn meter_keep_bars(&mut self, before: &MeterMap, after: &MeterMap, bar: u32);

    /// The meter changed from `bar` on and the music between `bar` and the next meter change is
    /// rewritten across the new barlines (behaviour (ii)): bars `bar..until_before` of the old map
    /// become bars `bar..until_after` of the new one, with the same total length, so the music
    /// after the region keeps its absolute positions. Re-tying across the new barlines is
    /// notation work, the same for every candidate, and is left out.
    fn meter_rewrite(
        &mut self,
        before: &MeterMap,
        after: &MeterMap,
        bar: u32,
        until_before: u32,
        until_after: u32,
    );

    /// A read-only copy for another thread.
    fn snapshot(&self) -> Self::Snapshot;

    /// Visits every event of every voice in order, with absolute positions.
    fn for_each(&self, meter: &MeterMap, f: impl FnMut(usize, Position, &Event));
}

// ---------------------------------------------------------------------------------------------
// Generated reference scores.
// ---------------------------------------------------------------------------------------------

/// The two reference scores of ANALYSIS.md §7.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Size {
    /// 100 bars × 10 staves.
    Normal,
    /// 1000 bars × 30 staves.
    Heavy,
}

/// A generated score: its meter map, its length in bars and the events of every voice in order.
pub struct Spec {
    /// The meter map of the score.
    pub meter: MeterMap,
    /// The number of bars (the document length).
    pub bars: u32,
    /// For every voice, its events with their absolute positions, sorted.
    pub voices: Vec<Vec<(Position, Event)>>,
    /// The next free ID (every note and event ID below it is taken).
    pub next_id: u64,
}

/// SplitMix64: a tiny deterministic generator, so every run builds the same scores.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    /// A number in `0..n`.
    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
}

/// Shorthand for a duration `n/d` of a whole note.
pub fn dur(n: i64, d: i64) -> Duration {
    Duration::from_rational(Rational::new(n, d).unwrap())
}

/// Shorthand for a meter `n/d`.
pub fn meter(n: u8, d: u16) -> MeterChange {
    MeterChange::new(Meter::new(&[n], d).unwrap())
}

/// The bar where the free cadenza of every reference score sits.
pub const FREE_BAR: u32 = 10;

/// The meter map of a reference score: 4/4, a free bar of two whole notes at bar 10, then every
/// hundred bars a short 6/8 section (bars 60–69, 160–169, …).
fn reference_meter(bars: u32) -> MeterMap {
    let mut map = MeterMap::new(meter(4, 4)).unwrap();
    map.set_irregular_bar(
        BarIndex::new(FREE_BAR),
        IrregularBar {
            length: dur(2, 1),
            kind: BarKind::Free,
        },
    )
    .unwrap();
    let mut base = 0;
    while base + 70 < bars {
        map.set_meter_change(BarIndex::new(base + 60), meter(6, 8))
            .unwrap();
        map.set_meter_change(BarIndex::new(base + 70), meter(4, 4))
            .unwrap();
        base += 100;
    }
    map
}

/// The voices of a reference score: `(staff, rhythmic profile)` for each voice.
///
/// The normal score has a piano (two staves, four voices) and eight one-staff instruments, two of
/// them with a second voice: 10 staves, 14 voices. The heavy score has two pianos and 26 one-staff
/// instruments, every fourth with a second voice: 30 staves, 41 voices.
fn reference_voices(size: Size) -> Vec<(u8, bool)> {
    let (pianos, singles) = match size {
        Size::Normal => (1, 8),
        Size::Heavy => (2, 26),
    };
    let mut voices = Vec::new();
    for _ in 0..pianos {
        // Staff numbers are per instrument (F2): 0 = upper, 1 = lower. The second voice of each
        // staff is a "secondary" (sparser) voice.
        voices.extend([(0, false), (0, true), (1, false), (1, true)]);
    }
    for i in 0..singles {
        voices.push((0, false));
        if i % 4 == 0 {
            voices.push((0, true));
        }
    }
    voices
}

/// Generates a reference score, deterministically.
///
/// Every voice fills every bar with a rhythmic unit chosen per voice (quarters, eighths,
/// sixteenths, triplet eighths, quintuplet sixteenths, halves), with 15% rests and chords of 1–4
/// notes; when the unit does not divide the rest of the bar (6/8 with triplets, the free bar), the
/// last event takes what is left. Every 8 bars a voice may switch to another unit.
pub fn generate(size: Size) -> Spec {
    let bars = match size {
        Size::Normal => 100,
        Size::Heavy => 1000,
    };
    let meter_map = reference_meter(bars);
    let units = [
        dur(1, 4),
        dur(1, 8),
        dur(1, 16),
        dur(1, 12),
        dur(1, 20),
        dur(1, 2),
    ];
    // Main voices: mostly quarters and eighths; secondary voices: halves and quarters.
    let main_weights = [45, 25, 8, 10, 2, 10];
    let secondary_weights = [50, 10, 0, 0, 0, 40];
    let mut rng = Rng(0x0F1_06);
    let mut next_id = 1_u64;
    let mut voices = Vec::new();
    for (staff, secondary) in reference_voices(size) {
        let weights = if secondary {
            &secondary_weights
        } else {
            &main_weights
        };
        let mut events = Vec::new();
        let mut unit = units[0];
        for bar in 0..bars {
            if bar % 8 == 0 {
                let total: u64 = weights.iter().sum();
                let mut pick = rng.below(total);
                for (i, &w) in weights.iter().enumerate() {
                    if pick < w {
                        unit = units[i];
                        break;
                    }
                    pick -= w;
                }
            }
            let start = meter_map.bar_start(BarIndex::new(bar)).unwrap();
            let length = meter_map.bar_length(BarIndex::new(bar)).unwrap();
            let mut offset = Duration::ZERO;
            while offset < length {
                let left = length.checked_sub(offset).unwrap();
                let duration = if unit > left { left } else { unit };
                let len = if rng.below(100) < 15 {
                    0
                } else {
                    match rng.below(100) {
                        0..82 => 1,
                        82..94 => 2,
                        94..98 => 3,
                        _ => 4,
                    }
                };
                let id = EventId(next_id);
                next_id += 1;
                let mut notes = [Note {
                    id: 0,
                    pitch: 0,
                    tied: false,
                }; 4];
                for note in notes.iter_mut().take(len) {
                    note.id = next_id;
                    next_id += 1;
                    note.pitch = 40 + rng.below(50) as i16;
                }
                let at = start.checked_add(offset).unwrap();
                events.push((
                    at,
                    Event {
                        id,
                        duration,
                        staff,
                        len: len as u8,
                        notes,
                    },
                ));
                offset = offset.checked_add(duration).unwrap();
            }
        }
        voices.push(events);
    }
    Spec {
        meter: meter_map,
        bars,
        voices,
        next_id,
    }
}

impl Spec {
    /// Number of events (chords and rests) and of noteheads.
    pub fn counts(&self) -> (usize, usize) {
        let events = self.voices.iter().map(Vec::len).sum();
        let notes = self
            .voices
            .iter()
            .flatten()
            .map(|(_, e)| usize::from(e.len))
            .sum();
        (events, notes)
    }
}

// ---------------------------------------------------------------------------------------------
// The measured edits: meter maps before/after, and the probes for the small operations.
// ---------------------------------------------------------------------------------------------

/// Number of small operations (insert, delete, find) per measurement: batches, as ADR-0017 §4
/// requires, so that one instruction of noise does not matter.
pub const BATCH: usize = 64;

/// The bar where a bar is inserted.
pub const INSERT_BAR: u32 = 30;
/// The bar where the meter changes (3/4 from bar 20, back to 4/4 at bar 32).
pub const METER_BAR: u32 = 20;
/// The end of the region of the meter change, before the edit.
pub const METER_UNTIL: u32 = 32;
/// The end of the region after a rewrite: 12 bars of 4/4 become 16 bars of 3/4.
pub const METER_UNTIL_REWRITTEN: u32 = 36;
/// The bars collected by [`Model::collect`]: a page of the score.
pub const COLLECT: Range<u32> = 40..60;

/// A copy of `map` where every entry at a bar `≥ from` moves `by` bars later.
pub fn shifted(map: &MeterMap, from: u32, by: u32) -> MeterMap {
    let shift = |b: BarIndex| {
        if b.get() >= from {
            BarIndex::new(b.get() + by)
        } else {
            b
        }
    };
    let changes = map.meter_changes();
    let mut out = MeterMap::new(changes[0].1.clone()).unwrap();
    for (bar, change) in &changes[1..] {
        out.set_meter_change(shift(*bar), change.clone()).unwrap();
    }
    for (bar, irregular) in map.irregular_bars() {
        out.set_irregular_bar(shift(*bar), *irregular).unwrap();
    }
    for (bar, grouping) in map.bar_groupings() {
        out.set_bar_grouping(shift(*bar), grouping.clone()).unwrap();
    }
    out
}

/// The meter map after inserting a regular bar at [`INSERT_BAR`].
pub fn after_insert_bar(map: &MeterMap) -> MeterMap {
    shifted(map, INSERT_BAR, 1)
}

/// The meter map after lengthening the free bar by a quarter.
pub fn after_lengthen(map: &MeterMap) -> MeterMap {
    let mut out = map.clone();
    out.set_irregular_bar(
        BarIndex::new(FREE_BAR),
        IrregularBar {
            length: dur(9, 4),
            kind: BarKind::Free,
        },
    )
    .unwrap();
    out
}

/// The meter map after the meter change with behaviour (i): bars 20–31 become 3/4 and keep their
/// (now too long) contents.
pub fn after_keep_bars(map: &MeterMap) -> MeterMap {
    let mut out = map.clone();
    out.set_meter_change(BarIndex::new(METER_BAR), meter(3, 4))
        .unwrap();
    out.set_meter_change(BarIndex::new(METER_UNTIL), meter(4, 4))
        .unwrap();
    out
}

/// The meter map after the meter change with behaviour (ii): the 12 bars of 4/4 from bar 20
/// become 16 bars of 3/4, and everything after them moves 4 bars later in numbering (but not in
/// absolute position).
pub fn after_rewrite(map: &MeterMap) -> MeterMap {
    let mut out = shifted(map, METER_UNTIL, METER_UNTIL_REWRITTEN - METER_UNTIL);
    out.set_meter_change(BarIndex::new(METER_BAR), meter(3, 4))
        .unwrap();
    out.set_meter_change(BarIndex::new(METER_UNTIL_REWRITTEN), meter(4, 4))
        .unwrap();
    out
}

/// The probes of the small operations: [`BATCH`] events to insert (voice, position, event) and
/// [`BATCH`] existing IDs, spread over the score and the voices.
pub struct Probes {
    /// Events to insert, each at the position of an existing event of its voice.
    pub inserts: Vec<(usize, Position, Event)>,
    /// Existing IDs, for delete and find.
    pub ids: Vec<EventId>,
}

/// Builds the probes of a score.
pub fn probes(spec: &Spec) -> Probes {
    let mut inserts = Vec::new();
    let mut ids = Vec::new();
    let mut next_id = spec.next_id;
    let voices = spec.voices.len();
    for k in 0..BATCH {
        let voice = k * 7 % voices;
        let events = &spec.voices[voice];
        let (at, event) = events[events.len() * (k * 37 % BATCH) / BATCH];
        ids.push(event.id);
        let mut new = event;
        new.id = EventId(next_id);
        next_id += 1;
        inserts.push((voice, at, new));
    }
    Probes { inserts, ids }
}

/// Every event of a model as `(voice, position, id)`, sorted: used by the tests to check that the
/// three candidates always hold the same music.
pub fn listing<M: Model>(model: &M, meter: &MeterMap) -> Vec<(usize, Position, EventId)> {
    let mut out = Vec::new();
    model.for_each(meter, |voice, at, event| out.push((voice, at, event.id)));
    out.sort();
    out
}
